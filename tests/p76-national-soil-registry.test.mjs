import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
import {buildNationalRegistry,checkNationalRegistry} from '../scripts/p76-national-soil-registry-audit.mjs';

const reg=JSON.parse(readFileSync('research/p76-national-soil-evidence-registry-v1.json','utf8'));
const verified=checkNationalRegistry(reg);
assert.equal(verified.status,'P76_NATIONAL_SOURCE_REGISTRY_PASS');
assert.equal(verified.prefectures,47);
assert.equal(verified.polygons,60863);
assert.equal(verified.foreign_jcode_unreported_prefectures,10);
assert.equal(verified.gun_blank_unreported_prefectures,31);
assert.equal(verified.rights_claims_verified,0);
const expected=buildNationalRegistry();
assert.equal(expected.records.length,47);
assert.deepEqual(expected.summary.landuse_counts,{'田':22755,'普通畑':20726,'牧草地':5327,'樹園地':12055});
assert.equal(expected.summary.zip_sha256_recorded_prefectures,47);
assert.equal(expected.summary.official_zip_sha256_match_verified_prefectures,0);
assert.equal(expected.summary.redistribution_rights_verified_prefectures,0);
assert.equal(expected.summary.quality_field_coverage.foreign_jcode_features.reported_prefectures,37);
assert.equal(expected.summary.quality_field_coverage.blank_gun_features.reported_prefectures,16);
assert.equal(expected.summary.quality_field_coverage.soil_group_missing_features.reported_counts_total,5);
assert.equal(new Set(expected.records.map(r=>r.prefecture_code)).size,47);
assert.equal(expected.records.find(r=>r.prefecture_code==='07').prefecture_name,'福島県');
assert.equal(expected.records.find(r=>r.prefecture_code==='47').prefecture_name,'沖縄県');
assert.equal(expected.records.find(r=>r.prefecture_code==='01').quality.foreign_jcode_features,null);
assert.equal(expected.records.find(r=>r.prefecture_code==='47').quality.foreign_jcode_features,0);
assert.equal(expected.records.find(r=>r.prefecture_code==='07').quality.blank_gun_features,null);

const tamper=JSON.parse(JSON.stringify(reg));
tamper.records[0].landuse_counts['田']++;
assert.throws(()=>checkNationalRegistry(tamper),/diverged/);
const wrongNull=JSON.parse(JSON.stringify(reg));
wrongNull.records[0].quality.foreign_jcode_features=0;
assert.throws(()=>checkNationalRegistry(wrongNull),/diverged/);
const forgedRights=JSON.parse(JSON.stringify(reg));
forgedRights.records[0].source.redistribution_rights='VERIFIED';
assert.throws(()=>checkNationalRegistry(forgedRights),/diverged/);
const badHash=JSON.parse(JSON.stringify(reg));
badHash.records[0].source.zip_sha256='not-real';
assert.throws(()=>checkNationalRegistry(badHash),/diverged/);

const audit=spawnSync('node',['scripts/p76-national-soil-registry-audit.mjs','--check'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).polygons,60863);

let forbiddenNetworkCalls=0;
const slot={isConnected:true,innerHTML:'',getAttribute:key=>key==='data-pref-code'?'07':null};
const gxEsc=s=>String(s==null?'':s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&#39;');
const ctx={gxEsc,fetch:()=>{forbiddenNetworkCalls++;throw Error('NETWORK_FORBIDDEN');},document:{getElementById:id=>id==='gx-national-soil-registry'?slot:null}};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-national-soil-registry.js','utf8'),ctx);
assert.ok(ctx.gxNationalSoilEvidencePanel('07').includes('data-pref-code="07"'));
assert.equal(ctx.gxNationalSoilRegistryValidate(reg),reg);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_NATIONAL_SOIL_REGISTRY_CACHE)),reg,'browser snapshot must equal audited JSON');
assert.ok(ctx.gxNationalSoilRegistryHtml(reg,'07').includes('福島県'));
ctx.gxNationalSoilEvidenceHydrate();
await ctx.gxNationalSoilRegistryLoad();
await new Promise(resolve=>setImmediate(resolve));
assert.equal(forbiddenNetworkCalls,0,'static registry must not call a network source');
for(const str of ['60,863','福島県','未記録','NOT_VERIFIED','47都道府県','10県','31県','research/p35-fukushima-soil-shapefile-source-v1.json'])
 assert.ok(slot.innerHTML.includes(str),'missing panel text: '+str);
assert.equal((slot.innerHTML.match(/>台帳 ↗<\/a>/g)||[]).length,47);
ctx.gxNationalSoilEvidenceHydrate();
await ctx.gxNationalSoilRegistryLoad();
assert.equal(forbiddenNetworkCalls,0,'rerender must remain offline');
const corrupted=JSON.parse(JSON.stringify(reg));
corrupted.records[0].source.zip_sha256='bad';
assert.throws(()=>ctx.gxNationalSoilRegistryValidate(corrupted),/P76_REGISTRY_PROVENANCE/);
const mismatch=JSON.parse(JSON.stringify(reg));
mismatch.records[0].polygon_features++;
assert.throws(()=>ctx.gxNationalSoilRegistryValidate(mismatch),/P76_REGISTRY_LAND_PARITY/);

const app=readFileSync('naft-app.html','utf8'),atlas=readFileSync('src/gx-data-explorer.js','utf8'),ui=readFileSync('src/mrv-ui.js','utf8'),runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-national-soil-registry.js'));
assert.ok(app.indexOf('src/gx-national-soil-registry.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxNationalSoilEvidencePanel(current.code)'));
assert.ok(ui.includes('gxNationalSoilEvidenceHydrate()'));
assert.ok(runner.includes('node scripts/p76-national-soil-registry-audit.mjs --check'));
assert.ok(runner.includes('node tests/p76-national-soil-registry.test.mjs'));
console.log('NAFT_P76_NATIONAL_47_LEDGER_60863_POLYGONS_SOURCE_PARITY_AND_QC_PASS');
