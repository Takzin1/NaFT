'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const code=fs.readFileSync('src/gikuten-ja.js','utf8');
const ctx={};
vm.runInNewContext(code,ctx,{filename:'src/gikuten-ja.js'});
assert.equal(ctx.gikutenTranslateText('Reviewer Demo'),'審査員向けデモ');
assert.equal(ctx.gikutenTranslateText('100 Claim変更影響実験を実行'),'100件の変更影響解析を実行');
assert.equal(ctx.gikutenTranslateText('Demo A · Evidence → draft'),'実演A｜証憑から下書きを自動生成');
assert.equal(ctx.gikutenTranslateText('Export attested package JSON'),'最終確認済みJSONを保存');
assert.equal(ctx.gikutenTranslateText('NAFT-SYNTHETIC@1'),'NAFT-SYNTHETIC@1');
assert.equal(ctx.gikutenTranslateText('120'), '120');
assert.equal(ctx.gikutenTranslateText('方法論の更新'), '方法論の更新');
const html=fs.readFileSync('gikuten.html','utf8');
assert.match(html,/lang="ja"/);
assert.match(html,/src="src\/gikuten-ja\.js"/);
assert.match(html,/src="src\/mrv-ui\.js"/);
assert.ok(html.indexOf('src/mrv-ui.js')<html.indexOf('src/gikuten-ja.js'));
assert.match(html,/#\/reviewer-demo/);
assert.match(html,/src="src\/gikuten.css"/);
assert.ok(fs.readFileSync('naft-app.html','utf8').includes('src/mrv-ui.js'));
console.log('技育展日本語版の表示文言・機械可読値・読み込み順を検証: OK');
