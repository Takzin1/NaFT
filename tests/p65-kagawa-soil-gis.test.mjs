import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p65-kagawa-soil-shapefile-source-v1.json','utf8'));
const hash='715f79859b59b29403ddb9b9e875074208c148cbc2fc4f4008d6392fa65858be';
assert.equal(m.schema,'naft-p65-kagawa-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,5394144);
assert.equal(m.source.uncompressed_bytes,8272630);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,508);
assert.equal(m.geometry.municipality_name_count,17);
assert.equal(m.geometry.unique_jcodes,20);
assert.deepEqual(m.feature_counts_by_landuse,{'田':217,'普通畑':141,'牧草地':7,'樹園地':143});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,44);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,23);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'36':10});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,10);
assert.equal(m.source_gun_quality.blank_gun_features,358);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,53);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p65-kagawa-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,508);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p65-kagawa-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P65_KAGAWA_SOURCE_BLOCKED:ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-kagawa-soil.js','utf8'),ctx);
assert.equal(ctx.gxKagawaSoilValidate(),true);
assert.equal(ctx.GX_KAGAWA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KAGAWA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KAGAWA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxKagawaSoilPanel('36'),'');
const html=ctx.gxKagawaSoilPanel('37');
for(const s of ['香川県の農耕地土壌GIS','508件','徳島県系JCODE','44組合せ','23組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
ctx.GX_KAGAWA_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKagawaSoilValidate(),/P65_KAGAWA_/);
ctx.GX_KAGAWA_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxKagawaSoilValidate(),true);
ctx.GX_KAGAWA_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKagawaSoilValidate(),/P65_KAGAWA_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-kagawa-soil.js'));
assert.ok(app.indexOf('src/gx-kagawa-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxTokushimaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxKagawaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p65-kagawa-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p65-kagawa-soil-gis.test.mjs'));
console.log('NAFT_P65_KAGAWA_508_POLYGONS_44_JCODE_PAIRS_23_GUN_PAIRS_PASS');
