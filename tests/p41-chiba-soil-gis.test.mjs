assert.ok(m.source.members.every(x=>x.name.startsWith('k12千葉県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.shape_count,1907);
assert.equal(m.geometry.municipality_name_count,57);
assert.equal(m.geometry.unique_jcodes,63);
assert.equal(m.geometry.administrative_code_name_pairs,179);
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(m.geometry.bounds_lon_lat,[139.753883054109,34.903491240950544,140.865870254935,36.10150344929939]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.gun_counts,{'':1514,'印旛郡':22,'夷隅郡':36,'安房郡':24,'山武郡':92,'猿島郡':1,'長生郡':153,'香取郡':65});
assert.deepEqual(m.chiba_gun_integrity.gun_feature_counts,m.geometry.gun_counts);
assert.equal(m.chiba_gun_integrity.suspected_foreign_gun_name,'猿島郡');
assert.deepEqual(m.chiba_gun_integrity.suspected_foreign_gun_records,[{'jcode':'08542','municipality_name':'野田市','gun':'猿島郡','landuse':'普通畑'}]);
assert.equal(m.chiba_gun_integrity.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');
assert.deepEqual(m.feature_counts_by_landuse,{'田':806,'普通畑':726,'牧草地':120,'樹園地':255});
