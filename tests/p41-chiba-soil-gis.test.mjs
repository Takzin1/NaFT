const rows=m.jcode_name_pairs_counts_by_landuse;
assert.equal(rows.length,179);
assert.equal(new Set(rows.map(r=>r[0])).size,63);
assert.equal(new Set(rows.map(r=>r[1])).size,57);
assert.equal(new Set(rows.map(r=>r[0]+'|'+r[1])).size,179);
assert.ok(rows.every(r=>r.length===6&&/^(08|11|12)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>rows.reduce((sum,r)=>sum+r[2+i],0)),[806,726,120,255]);
const a=m.source_code_name_anomalies, foreign=rows.filter(r=>!r[0].startsWith('12'));
assert.equal(foreign.length,6);
assert.equal(foreign.reduce((sum,r)=>sum+r.slice(2).reduce((x,y)=>x+y,0),0),8);
assert.deepEqual(foreign,a.foreign_prefecture_code_pairs);
assert.deepEqual(a.foreign_code_prefix_totals,{'08':7,'11':1});
assert.deepEqual(a.foreign_prefixes,['08','11']);
assert.equal(Object.keys(a.codes_with_multiple_names).length,42);
assert.equal(Object.keys(a.names_with_multiple_codes).length,49);
assert.deepEqual(a.historical_place_names_as_source,['大網白里町']);
assert.deepEqual(a.historical_place_name_polygon_counts,{'大網白里町':72});
assert.equal(rows.filter(r=>r[1]==='大網白里町').reduce((sum,r)=>sum+r.slice(2).reduce((x,y)=>x+y,0),0),72);
assert.equal(a.one_to_one_code_name_mapping,false);
assert.equal(a.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
