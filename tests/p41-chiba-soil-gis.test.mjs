assert.deepEqual(JSON.parse(JSON.stringify(box.GX_CHIBA_CODE_NAME_PAIRS)),rows);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_CHIBA_LANDUSE))),m.feature_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_CHIBA_GUN))),m.geometry.gun_counts);
