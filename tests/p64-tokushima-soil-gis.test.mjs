import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p64-tokushima-soil-shapefile-source-v1.json','utf8'));
const hash='2871b5b2f6f7d22840da9062b01684c67d2a221bcbfa21290362d21271d4c587';
assert.equal(m.schema,'naft-p64-tokushima-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,4553174);
assert.equal(m.source.uncompressed_bytes,7319034);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,692);
assert.equal(m.geometry.unique_jcodes,24);
assert.equal(m.geometry.municipality_name_count,24);
assert.deepEqual(m.feature_counts_by_landuse,{'田':291,'普通畑':203,'牧草地':29,'樹園地':169});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,51);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,38);
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,0);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{});
assert.equal(m.source_gun_quality.blank_gun_features,368);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,58);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{
  '神山町':['名東郡','名西郡'],'上板町':['名西郡','板野郡'],'美波町':['海部郡','那賀郡']});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p64-tokushima-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,692);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p64-tokushima-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P64_TOKUSHIMA_SOURCE_BLOCKED:ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-tokushima-soil.js','utf8'),ctx);
assert.equal(ctx.gxTokushimaSoilValidate(),true);
assert.equal(ctx.GX_TOKUSHIMA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_TOKUSHIMA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_TOKUSHIMA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxTokushimaSoilPanel('35'),'');
const html=ctx.gxTokushimaSoilPanel('36');
for(const s of ['徳島県の農耕地土壌GIS','692件','神山町','上板町','美波町','51組合せ','38組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
ctx.GX_TOKUSHIMA_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxTokushimaSoilValidate(),/P64_TOKUSHIMA_/);
ctx.GX_TOKUSHIMA_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxTokushimaSoilValidate(),true);
ctx.GX_TOKUSHIMA_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxTokushimaSoilValidate(),/P64_TOKUSHIMA_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-tokushima-soil.js'));
assert.ok(app.indexOf('src/gx-tokushima-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxYamaguchiSoilPanel(current.code)'));
assert.ok(atlas.includes('gxTokushimaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p64-tokushima-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p64-tokushima-soil-gis.test.mjs'));
console.log('NAFT_P64_TOKUSHIMA_692_POLYGONS_51_JCODE_PAIRS_38_GUN_PAIRS_PASS');
