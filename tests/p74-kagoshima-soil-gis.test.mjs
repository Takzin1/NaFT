import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p74-kagoshima-soil-shapefile-source-v1.json','utf8'));
const hash='26b91128ec49d96d48285157295e5aef2bc3b7fe464c24ac0349493bafc8e817';
assert.equal(m.schema,'naft-p74-kagoshima-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,14692127);
assert.equal(m.source.uncompressed_bytes,22462084);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1549);
assert.equal(m.geometry.municipality_name_count,41);
assert.equal(m.geometry.unique_jcodes,45);
assert.deepEqual(m.feature_counts_by_landuse,{'田':467,'普通畑':616,'牧草地':111,'樹園地':355});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,90);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,51);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'43':2,'45':24});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,26);
assert.equal(m.source_gun_quality.blank_gun_features,1039);
assert.equal(m.source_gun_quality.non_kagoshima_gun_name_feature_count,0);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,63);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{'東串良町':['曽於郡','肝属郡']});
assert.equal(m.soil_group_code_categories,23);
assert.equal(m.soil_fine_class_categories,108);
assert.equal(m.soil_group_missing_features,0);
assert.equal(m.soil_detail_missing_features,0);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p74-kagoshima-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,1549);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p74-kagoshima-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P74_KAGOSHIMA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-kagoshima-soil.js','utf8'),ctx);
assert.equal(ctx.gxKagoshimaSoilValidate(),true);
assert.equal(ctx.GX_KAGOSHIMA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KAGOSHIMA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KAGOSHIMA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxKagoshimaSoilPanel('45'),'');
const html=ctx.gxKagoshimaSoilPanel('46');
for(const term of ['鹿児島県の農耕地土壌GIS','1,549件','熊本県系JCODE','宮崎県系JCODE','43205','45202','東串良町','曽於郡','肝属郡','90組合せ','51組合せ','要照合','農地面積ha'])assert.ok(html.includes(term),term);
ctx.GX_KAGOSHIMA_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKagoshimaSoilValidate(),/P74_KAGOSHIMA_/);
ctx.GX_KAGOSHIMA_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxKagoshimaSoilValidate(),true);
ctx.GX_KAGOSHIMA_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKagoshimaSoilValidate(),/P74_KAGOSHIMA_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-kagoshima-soil.js'));
assert.ok(app.indexOf('src/gx-kagoshima-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxMiyazakiSoilPanel(current.code)'));
assert.ok(atlas.includes('gxKagoshimaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p74-kagoshima-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p74-kagoshima-soil-gis.test.mjs'));
console.log('NAFT_P74_KAGOSHIMA_1549_POLYGONS_90_JCODE_PAIRS_51_GUN_PAIRS_PASS');
