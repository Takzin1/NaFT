import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p62-hiroshima-soil-shapefile-source-v1.json','utf8'));
const hash='44953dd998ad968355c0d33dc910fd8806dd1a2064c4d1a10976902c0aafb626';
assert.equal(m.schema,'naft-p62-hiroshima-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,12206280);
assert.equal(m.source.members.length,7);
assert.equal(m.source.uncompressed_bytes,18739976);
assert.ok(m.source.members.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1209);
assert.equal(m.geometry.unique_jcodes,35);
assert.equal(m.geometry.municipality_name_count,29);
assert.deepEqual(m.feature_counts_by_landuse,{'田':478,'普通畑':407,'牧草地':125,'樹園地':199});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,62);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,36);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'32':4,'33':11});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,15);
assert.equal(m.source_gun_quality.blank_gun_features,991);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,250);
assert.equal(m.source_gun_quality.non_hiroshima_gun_name_feature_count,4);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p62-hiroshima-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,1209);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p62-hiroshima-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P62_HIROSHIMA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-hiroshima-soil.js','utf8'),context);
assert.equal(context.gxHiroshimaSoilValidate(),true);
assert.equal(context.GX_HIROSHIMA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_HIROSHIMA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_HIROSHIMA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(context.gxHiroshimaSoilPanel('33'),'');
const html=context.gxHiroshimaSoilPanel('34');
for(const s of ['広島県の農耕地土壌GIS','1,209件','県外系JCODE','仁多郡','邑智郡','62組合せ','36組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
context.GX_HIROSHIMA_CODE_PAIRS[0][2]++;
assert.throws(()=>context.gxHiroshimaSoilValidate(),/P62_HIROSHIMA_/);
context.GX_HIROSHIMA_CODE_PAIRS[0][2]--;
assert.equal(context.gxHiroshimaSoilValidate(),true);
context.GX_HIROSHIMA_GUN_PAIRS[0][2]++;
assert.throws(()=>context.gxHiroshimaSoilValidate(),/P62_HIROSHIMA_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-hiroshima-soil.js'));
assert.ok(app.indexOf('src/gx-hiroshima-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxOkayamaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxHiroshimaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p62-hiroshima-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p62-hiroshima-soil-gis.test.mjs'));
console.log('NAFT_P62_HIROSHIMA_1209_POLYGONS_62_JCODE_PAIRS_36_GUN_PAIRS_PASS');
