import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p53-shiga-soil-shapefile-source-v1.json','utf8'));
const sourceSHA='3fef4ebc36d2856543a0034f05815fb1961e37b9ad1a160883d2ad22a0229a19';
assert.equal(m.schema,'naft-p53-shiga-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'滋賀県.zip');
assert.equal(m.source.source_zip_sha256,sourceSHA);
assert.equal(m.source.zip_bytes,4887387);
assert.equal(m.source.uncompressed_bytes,7899584);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((a,r)=>a+r.bytes,0),7899584);
assert.ok(m.source.members.every(r=>r.name.startsWith('k25滋賀県.')&&/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(m.geometry.bounds_lon_lat,[135.7872572992245,34.79754192350782,136.43336700581398,35.671852353859066]);
assert.equal(m.geometry.shape_count,785);
assert.equal(m.geometry.municipality_name_count,19);
assert.equal(m.geometry.unique_jcodes,22);
assert.equal(m.geometry.administrative_code_name_pairs,51);
assert.deepEqual(m.geometry.sicho_counts,{'':785});
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.gun_counts,{'':662,'不破郡':1,'愛知郡':25,'犬上郡':41,'蒲生郡':56});
assert.deepEqual(m.feature_counts_by_landuse,{'田':410,'普通畑':257,'牧草地':9,'樹園地':109});
assert.equal(m.soil_group_code_categories,16);
assert.equal(m.soil_fine_class_categories,64);
assert.deepEqual(m.soil_column_missing_features,{'包括_統群':0,'統群コード':0,'亜群コード':0,'群コード':0});

const codePairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(codePairs.length,51);
assert.equal(new Set(codePairs.map(r=>r[0]+'|'+r[1])).size,51);
assert.equal(new Set(codePairs.map(r=>r[0])).size,22);
assert.equal(new Set(codePairs.map(r=>r[1])).size,19);
assert.deepEqual([0,1,2,3].map(i=>codePairs.reduce((a,r)=>a+r[i+2],0)),[410,257,9,109]);
const a=m.source_code_name_anomalies;
const foreign=codePairs.filter(r=>!r[0].startsWith('25'));
assert.deepEqual(foreign,[['21362','米原市',0,0,0,1],['24210','甲賀市',0,0,0,1],['24216','甲賀市',3,0,0,0]]);
assert.deepEqual(a.foreign_prefecture_code_pairs,foreign);
assert.equal(a.foreign_prefecture_code_feature_count,5);
assert.deepEqual(a.foreign_code_prefix_totals,{'21':1,'24':4});
assert.deepEqual(a.foreign_prefixes,['21','24']);
assert.equal(Object.keys(a.codes_with_multiple_names).length,14);
assert.equal(Object.keys(a.names_with_multiple_codes).length,15);
assert.equal(a.one_to_one_code_name_mapping,false);
assert.equal(a.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const gunPairs=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunPairs.length,27);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,27);
assert.deepEqual([0,1,2,3].map(i=>gunPairs.reduce((a,r)=>a+r[i+2],0)),[410,257,9,109]);
assert.deepEqual(gunPairs.find(r=>r[0]==='不破郡'),['不破郡','米原市',0,0,0,1]);
assert.deepEqual(gunPairs.find(r=>r[0]==='愛知郡'&&r[1]==='豊郷町'),['愛知郡','豊郷町',3,0,0,0]);
assert.deepEqual(gunPairs.find(r=>r[0]==='犬上郡'&&r[1]==='豊郷町'),['犬上郡','豊郷町',7,3,0,0]);
const q=m.source_gun_quality;
assert.equal(q.empty_gun_features_for_names_with_county_elsewhere,94);
assert.equal(q.empty_gun_features_in_town_village_names,38);
assert.equal(q.city_name_empty_gun_features_with_county_elsewhere,56);
assert.equal(q.empty_gun_name_pairs_with_nonempty_gun_elsewhere.reduce((sum,r)=>sum+r.empty_gun_polygon_count,0),94);
assert.deepEqual(q.municipality_names_with_multiple_nonempty_guns,{'豊郷町':['愛知郡','犬上郡']});
assert.equal(q.non_shiga_gun_pairs[0].polygon_count,1);
assert.equal(q.non_shiga_gun_pairs[0].gun,'不破郡');
assert.equal(q.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.raw_geometry_licensed_for_publication,false);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const audit=spawnSync('python3',['scripts/p53-shiga-soil-audit.py','audit'],{encoding:'utf8',timeout:20000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(JSON.parse(audit.stdout).raw_original_verified_in_ci,false);
const tamper=spawnSync('python3',['scripts/p53-shiga-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:20000});
assert.notEqual(tamper.status,0);
assert.match(tamper.stderr,/P53_SHIGA_SOURCE_BLOCKED:ZIP_BYTES/);

const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-shiga-soil.js','utf8'),context);
assert.equal(context.gxShigaSoilValidate(),true);
assert.equal(context.GX_SHIGA_SOURCE_HASH,sourceSHA);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_SHIGA_CODE_NAME_PAIRS)),codePairs);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_SHIGA_GUN_NAME_PAIRS)),gunPairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_SHIGA_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_SHIGA_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(context.gxShigaSoilPanel('24'),'');
assert.equal(context.gxShigaSoilPanel('23'),'');
const html=context.gxShigaSoilPanel('25');
assert.match(html,/滋賀県の農耕地土壌GIS/);
assert.match(html,/785件/);
assert.match(html,/51通り/);
assert.match(html,/27組合せ/);
assert.match(html,/県外コード/);
assert.match(html,/不破郡/);
assert.match(html,/豊郷町/);
assert.match(html,/94件/);
assert.match(html,/38件/);
assert.match(html,/56件/);
assert.match(html,/主要4分類列の原本空欄は0件/);
assert.match(html,/面積haではありません/);
assert.match(html,/要照合/);
assert.match(html,/p53-shiga-soil-shapefile-source-v1.json/);
context.GX_SHIGA_CODE_NAME_PAIRS[0][5]++;
assert.throws(()=>context.gxShigaSoilValidate(),/P53_SHIGA_/);
context.GX_SHIGA_CODE_NAME_PAIRS[0][5]--;
context.GX_SHIGA_GUN_NAME_PAIRS.find(r=>r[0]==='不破郡')[5]++;
assert.throws(()=>context.gxShigaSoilValidate(),/P53_SHIGA_/);

const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.includes('src/gx-shiga-soil.js'));
assert.ok(app.indexOf('src/gx-shiga-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxShigaSoilPanel(current.code)'));
