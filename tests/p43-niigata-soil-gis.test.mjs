assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,86);
assert.equal(new Set(pairs.map(r=>r[0])).size,37);
assert.equal(new Set(pairs.map(r=>r[1])).size,37);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,86);
assert.ok(pairs.every(r=>r.length===6&&/^15[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[i+2],0)),[682,524,86,211]);
const a=m.source_code_name_anomalies;
assert.equal(a.foreign_prefecture_code_feature_count,0);
assert.deepEqual(a.foreign_prefecture_code_pairs,[]);
assert.deepEqual(a.foreign_prefixes,[]);
assert.deepEqual(a.foreign_code_prefix_totals,{});
assert.equal(Object.keys(a.codes_with_multiple_names).length,21);
assert.equal(Object.keys(a.names_with_multiple_codes).length,25);
assert.equal(a.one_to_one_code_name_mapping,false);
assert.equal(a.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
assert.deepEqual(a.codes_with_multiple_names['15202'],['三条市','出雲崎町','刈羽村','十日町市','小千谷市','燕市','見附市','長岡市','魚沼市']);
const gp=m.gun_name_pairs_counts_by_landuse;
assert.equal(gp.length,45);
assert.equal(new Set(gp.map(r=>r[0]+'|'+r[1])).size,45);
assert.deepEqual([0,1,2,3].map(i=>gp.reduce((a,r)=>a+r[2+i],0)),[682,524,86,211]);
const guns=Object.fromEntries([...new Set(gp.map(r=>r[0]))].map(g=>[g,gp.filter(r=>r[0]===g).reduce((sum,r)=>sum+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(guns,m.geometry.gun_counts);
const audited=spawnSync('python3',['scripts/p43-niigata-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audited.status,0,audited.stderr);
const auditedResult=JSON.parse(audited.stdout);
assert.equal(auditedResult.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(auditedResult.raw_original_verified_in_ci,false);
assert.equal(auditedResult.jcode_name_pairs,86);
const rejected=spawnSync('python3',['scripts/p43-niigata-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(rejected.status,0);
assert.match(rejected.stderr,/P43_NIIGATA_SOURCE_BLOCKED:ZIP_SIZE/);

