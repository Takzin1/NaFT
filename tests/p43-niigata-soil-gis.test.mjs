const m=JSON.parse(readFileSync('research/p43-niigata-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p43-niigata-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'新潟県.zip');
assert.equal(m.source.source_zip_sha256,'7e1e4877d7d7b9443b1bfc34fb71d1333fbfa4949a626837ee1fb83b6ff0246f');
assert.equal(m.source.zip_bytes,17478591);
assert.equal(m.source.uncompressed_bytes,26728304);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((sum,r)=>sum+r.bytes,0),26728304);
assert.ok(m.source.members.every(r=>r.name.startsWith('k18新潟県.')&&/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,1503);
assert.equal(m.geometry.municipality_name_count,37);
assert.equal(m.geometry.unique_jcodes,37);
assert.equal(m.geometry.administrative_code_name_pairs,86);
assert.deepEqual(m.geometry.bounds_lon_lat,[137.6363794713516,36.84500778396874,139.68688147974075,38.54217014257465]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':1503});
assert.deepEqual(m.geometry.gun_counts,{'':1345,'三島郡':10,'中魚沼郡':18,'刈羽郡':7,'北蒲原郡':20,'南蒲原郡':11,'南魚沼郡':6,'岩船郡':31,'東蒲原郡':42,'西蒲原郡':13});
assert.equal(m.soil_group_code_categories,19);
assert.equal(m.soil_fine_class_categories,78);
assert.deepEqual(m.feature_counts_by_landuse,{'田':682,'普通畑':524,'牧草地':86,'樹園地':211});
