import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const reg=JSON.parse(readFileSync('research/p34-akita-soil-shapefile-source-v1.json','utf8'));
assert.equal(reg.schema,'naft-p34-akita-soil-shapefile-v1');
assert.equal(reg.source.zip_bytes,10481614);
assert.equal(reg.source.uncompressed_bytes,16098322);
assert.equal(reg.source.source_zip_sha256,'3c5b27c3d7da16265add6de7958e10d0cd7cee286d7de093d8f3df760621fa34');
assert.equal(reg.source.members.length,7);
assert.equal(reg.source.members.reduce((s,m)=>s+m.bytes,0),16098322);
assert.ok(reg.source.members.every(m=>/^[a-f0-9]{64}$/.test(m.sha256) && m.name.startsWith('k5秋田県.')));
assert.equal(reg.source.original_zip_committed,false);
assert.equal(reg.source.raw_geometry_committed,false);
assert.equal(reg.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(reg.geometry.shape_count,1046);
assert.equal(reg.geometry.municipalities,25);
assert.deepEqual(reg.geometry.sicho_unique_values,['']);
assert.equal(reg.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(reg.geometry.bounds_lon_lat,[139.69867954562713,38.9384878368476,140.97844407518144,40.42182813770626]);
assert.deepEqual(reg.feature_counts_by_landuse,{'田':432,'普通畑':342,'牧草地':113,'樹園地':159});
assert.equal(reg.soil_group_code_categories,17);
assert.equal(reg.soil_fine_class_categories,79);
assert.equal(reg.scientific_boundaries.official_credit_tco2e,null);
assert.equal(reg.scientific_boundaries.raw_geometry_licensed_for_publication,false);
assert.equal(reg.municipalities_counts_by_landuse.length,25);
assert.equal(new Set(reg.municipalities_counts_by_landuse.map(row=>row[0])).size,25);
assert.ok(reg.municipalities_counts_by_landuse.every(row=>/^05[0-9]{3}$/.test(row[0])));
assert.deepEqual([0,1,2,3].map(i=>reg.municipalities_counts_by_landuse.reduce((s,row)=>s+row[i+2],0)),[432,342,113,159]);
const result=spawnSync('python3',['scripts/p34-akita-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(result.status,0,result.stderr);
assert.equal(JSON.parse(result.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const wrong=spawnSync('python3',['scripts/p34-akita-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(wrong.status,0);
assert.match(wrong.stderr,/P34_AKITA_SOURCE_BLOCKED:ZIP_SIZE/);
const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-akita-soil.js','utf8'),box);
assert.equal(box.gxAkitaSoilValidate(),true);
assert.equal(box.GX_AKITA_SOURCE_HASH,reg.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_AKITA_MUNICIPALITIES)),reg.municipalities_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_AKITA_LANDUSE))),reg.feature_counts_by_landuse);
assert.equal(box.gxAkitaSoilPanel('01'),'');
assert.equal(box.gxAkitaSoilPanel('06'),'');
const html=box.gxAkitaSoilPanel('05');
assert.match(html,/秋田県の農耕地土壌GIS/);
assert.match(html,/1,046/);
assert.match(html,/25市町村/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,26);
box.GX_AKITA_MUNICIPALITIES[0][2]++;
assert.throws(()=>box.gxAkitaSoilValidate(),/P34_AKITA_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-akita-soil.js')>0);
assert.ok(app.indexOf('src/gx-akita-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxAkitaSoilPanel(current.code)'));
for(const name of ['Hokkaido','Aomori','Iwate','Miyagi','Yamagata']){
 assert.ok(gx.includes('gx'+name+'SoilPanel(current.code)'));
}
console.log('NAFT_P34_AKITA_SOIL_GIS_INTAKE_AND_UI_PASS');
