import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const batch1=JSON.parse(readFileSync('research/p21-jaxa-lulc-2024-v25-04-batch01.json','utf8'));
const batch2=JSON.parse(readFileSync('research/p22-jaxa-lulc-2024-v25-04-batch02.json','utf8'));
assert.equal(batch2.schema,'naft-p22-jaxa-lulc-2024-v25-04-batch02');
assert.equal(batch2.version,batch1.version);
assert.equal(batch2.year,batch1.year);
assert.equal(batch2.rasters.length,1);
const newest=batch2.rasters[0];
assert.equal(newest.id,'LC_N30E129');
assert.equal(newest.pixels,144000000);
assert.equal(newest.water_pixels,143766652);
assert.equal(newest.paddy_pixels,0);
assert.equal(newest.count_by_class.reduce((a,b)=>a+b,0),newest.pixels);
assert.equal(newest.count_by_class[0],newest.water_pixels);
assert.equal(newest.count_by_class[2],newest.paddy_pixels);
assert.equal(newest.ha,null);assert.equal(batch2.official_credit_tco2e,null);
assert.equal(batch2.complete_national_coverage,false);
assert.equal(batch2.original_geotiff_committed,false);
assert.equal(batch2.original_geotiff_redistribution_permission_verified,false);
const scope={};
vm.createContext(scope);
vm.runInContext(readFileSync('src/gx-jaxa-landcover-2024.js','utf8'),scope);
assert.equal(scope.gxJaxaValidate(),true);
const tiles=JSON.parse(JSON.stringify(scope.GX_JAXA_TILES));
assert.equal(tiles.length,16);
assert.equal(new Set(tiles.map(t=>t.id)).size,16);
for(let i=0;i<3;i++){
 const src=batch1.tiles[i];
 assert.equal(tiles[i].id,src.id);
 assert.deepEqual(tiles[i].counts,src.count_by_class);
}
const uiTile=tiles.find(t=>t.id===newest.id);
assert.ok(uiTile);
assert.deepEqual(uiTile.bounds,newest.bounds);
assert.deepEqual(uiTile.counts,newest.count_by_class);
assert.equal(uiTile.water,newest.water_pixels);
assert.equal(uiTile.paddy,newest.paddy_pixels);
scope.GX_JAXA_SELECTED_TILE='LC_N30E129';
const html=scope.gxJaxaLandcoverPanel();
assert.match(html,/143,766,652/);
assert.match(html,/16枚/);
assert.match(html,/東経129〜130/);
assert.match(html,/GeoTIFF/);
assert.equal((html.match(/<option value=/g)||[]).length,16);
const smoke=readFileSync('tests/browser-gx-data-smoke.mjs','utf8');
assert.match(smoke,/JAXA batch2/);
