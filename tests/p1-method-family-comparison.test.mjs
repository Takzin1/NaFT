import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {loadRegistry} from '../scripts/rice-methodology-router.mjs';
import {buildP1Comparison,renderP1JapaneseMarkdown}
 from '../scripts/p1-method-family-comparison.mjs';
const result=buildP1Comparison(),raw=JSON.stringify(result),r=result.programs;
assert.equal(result.status,'REFERENCE_MAPPING_ONLY_NOT_SCIENTIFIC_OR_FORMAL_VALIDATION');
assert.equal(r.length,3);
assert.deepEqual(r.map(p=>p.lanes.length),[3,3,0]);
assert.equal(r[0].tier_1_3_document_conflict,'UNRESOLVED');
assert.equal(r[2].version,'CURRENT_ADOPTED_VERSION_UNVERIFIED');
assert.equal(result.cross_program_equivalence.automatic,false);
assert.equal(result.final_certified_tco2e,null);
assert.equal(result.third_party_publisher_origin_verified,false);
assert.equal(result.gold_full_workbook_replayed,false);
assert.equal(result.actual_field_observation_approved,false);
assert.equal(r[0].lanes.every(x=>x.formula.startsWith('=')&&x.educational_arithmetic_available),true);
assert.equal(r[1].lanes.every(x=>x.formula===null&&!x.educational_arithmetic_available),true);
assert.equal(r[0].lanes[0].description_ja,'簡易排出係数');
assert.equal(r[1].lanes[1].description_ja,'フラックスチャンバーによる直接測定');
assert.equal(raw.includes('certified_tco2e":null'),true);
const md=renderP1JapaneseMarkdown(result);
assert.match(md,/Gold StandardワークブックとVVBチェックリストQ23/);
assert.match(md,/J-クレジットAG-005の現行採択版/);
assert.match(md,/正式に認証されたtCO2e：未算定/);
assert.match(md,new RegExp(result.report_sha256));
assert.throws(()=>renderP1JapaneseMarkdown({...result,final_certified_tco2e:100}),/REPORT_SHA_MISMATCH/);
const changed=structuredClone(loadRegistry());
changed.programs.GS_AWD_TRAINING_2024.selection_conflict.resolution='RESOLVED';
assert.throws(()=>buildP1Comparison(changed),/GS_TIER_Q23_CONFLICT_LOST/);
const modified=structuredClone(loadRegistry());
modified.programs.VERRA_VM0051_V1_1_2026.lanes.QA2_DIRECT_CHAMBER.kind='EDDY_COVARIANCE';
assert.throws(()=>buildP1Comparison(modified),/VERRA_QA_DEFINITION_CHANGED/);
const cmd=(format)=>spawnSync(process.execPath,['scripts/p1-method-family-comparison.mjs','--format',format],{encoding:'utf8',timeout:15000});
const ja=cmd('markdown');assert.equal(ja.status,0);assert.equal(ja.stdout,md);
const json=cmd('json');assert.equal(json.status,0);assert.deepEqual(JSON.parse(json.stdout),result);
const bad=cmd('certified');assert.notEqual(bad.status,0);assert.equal(bad.stdout,'');
console.log('NAFT_P1_METHOD_FAMILY_COMPARISON_PASS: namespaces isolated, Japanese report, no automatic certification');
