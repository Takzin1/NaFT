import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p42-kanagawa-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p42-kanagawa-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'神奈川県.zip');
assert.equal(m.source.source_zip_sha256,'997a9ceac06fd70c2223cfb086f4aebc9ad38a74070fa43fe7bf80797ad84282');
assert.equal(m.source.zip_bytes,2684622);
assert.equal(m.source.uncompressed_bytes,5082502);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((sum,x)=>sum+x.bytes,0),5082502);
assert.ok(m.source.members.every(x=>x.name.startsWith('k14神奈川県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,1060);
assert.equal(m.geometry.municipality_name_count,52);
assert.equal(m.geometry.unique_jcodes,55);
assert.equal(m.geometry.administrative_code_name_pairs,128);
assert.deepEqual(m.geometry.bounds_lon_lat,[139.0015703824738,35.132446443281,139.70958906726077,35.66027242266548]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':1060});
assert.deepEqual(m.geometry.gun_counts,{'':885,'三浦郡':4,'中郡':46,'愛甲郡':18,'足柄上郡':67,'足柄下郡':18,'高座郡':22});
assert.equal(m.soil_group_code_categories,17);
assert.equal(m.soil_fine_class_categories,63);
assert.deepEqual(m.feature_counts_by_landuse,{'田':262,'普通畑':499,'牧草地':7,'樹園地':292});
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,128);
assert.equal(new Set(pairs.map(r=>r[0])).size,55);
assert.equal(new Set(pairs.map(r=>r[1])).size,52);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,128);
assert.ok(pairs.every(r=>r.length===6&&/^(13|14)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[2+i],0)),[262,499,7,292]);
const anomalies=m.source_code_name_anomalies;
const foreign=pairs.filter(r=>r[0].startsWith('13'));
assert.equal(foreign.length,6);
assert.equal(foreign.reduce((sum,r)=>sum+r.slice(2).reduce((a,b)=>a+b,0),0),18);
assert.deepEqual(foreign,anomalies.foreign_prefecture_code_pairs);
assert.deepEqual(anomalies.foreign_prefixes,['13']);
assert.deepEqual(anomalies.foreign_code_prefix_totals,{'13':18});
assert.equal(Object.keys(anomalies.codes_with_multiple_names).length,36);
assert.equal(Object.keys(anomalies.names_with_multiple_codes).length,39);
assert.equal(anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
assert.equal(anomalies.one_to_one_code_name_mapping,false);

const gunPairs=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunPairs.length,63);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,63);
assert.deepEqual([0,1,2,3].map(i=>gunPairs.reduce((a,r)=>a+r[2+i],0)),[262,499,7,292]);
const gunMap=Object.fromEntries([...new Set(gunPairs.map(r=>r[0]))].map(g=>[g,gunPairs.filter(r=>r[0]===g).reduce((sum,r)=>sum+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(gunMap,m.geometry.gun_counts);
assert.deepEqual(gunPairs.find(r=>r[0]==='中郡'&&r[1]==='中井町'),['中郡','中井町',1,0,0,1]);
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs.length,1);
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs[0].jcode,'14342');
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs[0].polygons,2);
assert.equal(m.source_gun_anomalies.resolution,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_NORMALIZATION');

const audited=spawnSync('python3',['scripts/p42-kanagawa-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audited.status,0,audited.stderr);
const result=JSON.parse(audited.stdout);
assert.equal(result.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(result.polygons,1060);
assert.equal(result.raw_original_verified_in_ci,false);
const reject=spawnSync('python3',['scripts/p42-kanagawa-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(reject.status,0);
assert.match(reject.stderr,/P42_KANAGAWA_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-kanagawa-soil.js','utf8'),box);
assert.equal(box.gxKanagawaSoilValidate(),true);
assert.equal(box.GX_KANAGAWA_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_KANAGAWA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_KANAGAWA_GUN_NAME_PAIRS)),gunPairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_KANAGAWA_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_KANAGAWA_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(box.gxKanagawaSoilPanel('13'),'');
assert.equal(box.gxKanagawaSoilPanel('12'),'');
const html=box.gxKanagawaSoilPanel('14');
assert.match(html,/神奈川県の農耕地土壌GIS/);
assert.match(html,/1,060件/);
assert.match(html,/52種類/);
assert.match(html,/128通り/);
assert.match(html,/18ポリゴン/);
assert.match(html,/GUN「中郡／中井町」/);
assert.match(html,/田1・樹園地1/);
assert.match(html,/要照合/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,200); // 6 GUN + 63 GUN/name + 128 JCODE/name + 3 header rows
box.GX_KANAGAWA_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxKanagawaSoilValidate(),/P42_KANAGAWA_CODE_NAME_ANOMALY/);
box.GX_KANAGAWA_CODE_NAME_PAIRS[0][2]--;
box.GX_KANAGAWA_CODE_NAME_PAIRS[7][2]++;
assert.throws(()=>box.gxKanagawaSoilValidate(),/P42_KANAGAWA_TOTAL/);
box.GX_KANAGAWA_CODE_NAME_PAIRS[7][2]--;
box.GX_KANAGAWA_GUN_NAME_PAIRS.find(r=>r[0]==='中郡'&&r[1]==='中井町')[2]++;
assert.throws(()=>box.gxKanagawaSoilValidate(),/P42_KANAGAWA_GUN_PARITY|P42_KANAGAWA_GUN_TOTAL|P42_KANAGAWA_NAKAI_GUN/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-kanagawa-soil.js')>0);
assert.ok(app.indexOf('src/gx-kanagawa-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxKanagawaSoilPanel(current.code)'));
for(const name of ['Hokkaido','Aomori','Iwate','Miyagi','Yamagata','Akita','Fukushima','Ibaraki','Tochigi','Saitama','Gunma','Tokyo','Chiba']){
 assert.ok(atlas.includes('gx'+name+'SoilPanel(current.code)'));
}
