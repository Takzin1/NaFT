import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p47-yamanashi-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p47-yamanashi-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'山梨県.zip');
assert.equal(m.source.source_zip_sha256,'78df028c3de6bd2e4544cd12f6f7aca98aa5a9af7de60b1bd574a4fa1c5f1842');
assert.equal(m.source.zip_bytes,3411194);
assert.equal(m.source.uncompressed_bytes,5546850);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((a,x)=>a+x.bytes,0),5546850);
assert.ok(m.source.members.every(x=>x.name.startsWith('k15山梨県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,564);
assert.equal(m.geometry.municipality_name_count,27);
assert.equal(m.geometry.unique_jcodes,28);
assert.equal(m.geometry.administrative_code_name_pairs,54);
assert.deepEqual(m.geometry.bounds_lon_lat,[138.23930161753367,35.18602299506912,139.12879005173434,35.948501229692546]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':564});
assert.deepEqual(m.geometry.gun_counts,{'':396,'中巨摩郡':14,'北都留郡':10,'南巨摩郡':75,'南都留郡':41,'西八代郡':28});
assert.deepEqual(m.feature_counts_by_landuse,{'田':163,'普通畑':193,'牧草地':18,'樹園地':190});
assert.equal(m.soil_group_code_categories,13);
assert.equal(m.soil_fine_class_categories,51);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,54);
assert.equal(new Set(pairs.map(r=>r[0])).size,28);
assert.equal(new Set(pairs.map(r=>r[1])).size,27);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,54);
assert.ok(pairs.every(r=>r.length===6&&/^(14|19)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[2+i],0)),[163,193,18,190]);
const foreign=pairs.filter(r=>r[0].startsWith('14'));
assert.deepEqual(foreign,[['14151','上野原市',0,1,0,0]]);
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,1);
assert.deepEqual(m.source_code_name_anomalies.foreign_prefecture_code_pairs,foreign);
assert.deepEqual(m.source_code_name_anomalies.foreign_prefixes,['14']);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'14':1});
assert.equal(Object.keys(m.source_code_name_anomalies.codes_with_multiple_names).length,14);
assert.equal(Object.keys(m.source_code_name_anomalies.names_with_multiple_codes).length,17);
assert.equal(m.source_code_name_anomalies.one_to_one_code_name_mapping,false);
assert.equal(m.source_code_name_anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const gunPairs=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunPairs.length,35);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,35);
assert.deepEqual([0,1,2,3].map(i=>gunPairs.reduce((a,r)=>a+r[2+i],0)),[163,193,18,190]);
const gunMap=Object.fromEntries([...new Set(gunPairs.map(r=>r[0]))].map(g=>[g,gunPairs.filter(r=>r[0]===g).reduce((sum,r)=>sum+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(gunMap,m.geometry.gun_counts);
const quality=m.source_gun_quality;
assert.equal(quality.empty_gun_features_for_known_gun_towns,21);
assert.deepEqual(quality.empty_gun_name_pairs_with_nonempty_gun_elsewhere.map(x=>[x.municipality_name,x.empty_gun_polygon_count]),[['富士川町',4],['富士河口湖町',1],['市川三郷町',4],['忍野村',1],['昭和町',9],['西桂町',2]]);
assert.deepEqual(quality.municipality_names_with_multiple_nonempty_guns,{'富士川町':['南巨摩郡','西八代郡'],'身延町':['南巨摩郡','西八代郡']});
assert.deepEqual(gunPairs.filter(r=>r[0]==='西八代郡'&&(r[1]==='富士川町'||r[1]==='身延町')),[['西八代郡','富士川町',0,1,0,0],['西八代郡','身延町',1,1,0,1]]);
assert.equal(quality.suspected_historical_gun_name_pairs.reduce((s,r)=>s+r.polygon_count,0),4);
assert.equal(quality.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');

const audit=spawnSync('python3',['scripts/p47-yamanashi-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const audited=JSON.parse(audit.stdout);
assert.equal(audited.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(audited.polygons,564);
assert.equal(audited.raw_original_verified_in_ci,false);
const invalid=spawnSync('python3',['scripts/p47-yamanashi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P47_YAMANASHI_SOURCE_BLOCKED:ZIP_SIZE/);

const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-yamanashi-soil.js','utf8'),ctx);
assert.equal(ctx.gxYamanashiSoilValidate(),true);
assert.equal(ctx.GX_YAMANASHI_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_YAMANASHI_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_YAMANASHI_GUN_NAME_PAIRS)),gunPairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(ctx.GX_YAMANASHI_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(ctx.GX_YAMANASHI_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(ctx.gxYamanashiSoilPanel('14'),'');
assert.equal(ctx.gxYamanashiSoilPanel('18'),'');
const html=ctx.gxYamanashiSoilPanel('19');
assert.match(html,/山梨県の農耕地土壌GIS/);
assert.match(html,/564件/);
assert.match(html,/193件/);
assert.match(html,/54組合せ/);
assert.match(html,/14151／上野原市/);
assert.match(html,/郡名付き記録のある市町村でも21ポリゴン/);
assert.match(html,/富士川町・身延町/);
assert.match(html,/西八代郡/);
assert.match(html,/要照合/);
assert.match(html,/面積haではありません/);
assert.match(html,/原本監査台帳/);
assert.equal((html.match(/<tr>/g)||[]).length,97); // 54 JCODE +35 GUN pairs +5 nonblank GUN +3 headers

ctx.GX_YAMANASHI_CODE_NAME_PAIRS[0][3]++;
assert.throws(()=>ctx.gxYamanashiSoilValidate(),/P47_YAMANASHI_FOREIGN_CODE_ANOMALY/);
ctx.GX_YAMANASHI_CODE_NAME_PAIRS[0][3]--;
ctx.GX_YAMANASHI_CODE_NAME_PAIRS[5][2]++;
assert.throws(()=>ctx.gxYamanashiSoilValidate(),/P47_YAMANASHI_TOTAL/);
ctx.GX_YAMANASHI_CODE_NAME_PAIRS[5][2]--;
ctx.GX_YAMANASHI_GUN_NAME_PAIRS.find(r=>r[0]==='西八代郡'&&r[1]==='富士川町')[3]++;
assert.throws(()=>ctx.gxYamanashiSoilValidate(),/P47_YAMANASHI_GUN_PARITY|P47_YAMANASHI_HISTORICAL_GUN/);

