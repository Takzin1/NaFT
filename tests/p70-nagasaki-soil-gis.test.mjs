import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const ledger=JSON.parse(readFileSync('research/p70-nagasaki-soil-shapefile-source-v1.json','utf8'));
const HASH='b164c6fdbdea997356b05f6658005d2acc855916d2837ec459aed994fc764b1e';
assert.equal(ledger.schema,'naft-p70-nagasaki-soil-shapefile-v1');
assert.equal(ledger.source.source_zip_sha256,HASH);
assert.equal(ledger.source.zip_bytes,7239387);
assert.equal(ledger.source.uncompressed_bytes,11235300);
assert.equal(ledger.source.members.length,7);
assert.ok(ledger.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(ledger.source.original_zip_committed,false);
assert.equal(ledger.source.raw_geometry_committed,false);
assert.equal(ledger.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(ledger.geometry.shape_count,863);
assert.equal(ledger.geometry.municipality_name_count,21);
assert.equal(ledger.geometry.unique_jcodes,26);
assert.deepEqual(ledger.feature_counts_by_landuse,{'田':327,'普通畑':290,'牧草地':27,'樹園地':219});
assert.equal(ledger.jcode_name_pairs_counts_by_landuse.length,46);
assert.equal(ledger.gun_name_pairs_counts_by_landuse.length,30);
assert.deepEqual(ledger.source_code_name_anomalies.foreign_code_prefix_totals,{'41':19});
assert.equal(ledger.source_code_name_anomalies.foreign_prefecture_code_feature_count,19);
assert.equal(ledger.source_gun_quality.blank_gun_features,680);
assert.equal(ledger.source_gun_quality.non_nagasaki_gun_name_feature_count,11);
assert.equal(ledger.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,159);
assert.deepEqual(ledger.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{'波佐見町':['東彼杵郡','西松浦郡']});
assert.equal(ledger.soil_group_code_categories,20);
assert.equal(ledger.soil_fine_class_categories,80);
assert.equal(ledger.soil_group_missing_features,0);
assert.equal(ledger.soil_detail_missing_features,0);
assert.equal(ledger.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const publicAudit=spawnSync('python3',['scripts/p70-nagasaki-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(publicAudit.status,0,publicAudit.stderr);
assert.equal(JSON.parse(publicAudit.stdout).features,863);
assert.equal(JSON.parse(publicAudit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p70-nagasaki-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P70_NAGASAKI_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-nagasaki-soil.js','utf8'),ctx);
assert.equal(ctx.gxNagasakiSoilValidate(),true);
assert.equal(ctx.GX_NAGASAKI_SOURCE_SHA,HASH);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_NAGASAKI_CODE_PAIRS)),ledger.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_NAGASAKI_GUN_PAIRS)),ledger.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxNagasakiSoilPanel('41'),'');
const html=ctx.gxNagasakiSoilPanel('42');
for(const word of ['長崎県の農耕地土壌GIS','863件','佐賀県系JCODE','藤津郡','西松浦郡','波佐見町','46組合せ','30組合せ','要照合','農地面積ha'])assert.ok(html.includes(word),word);
ctx.GX_NAGASAKI_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxNagasakiSoilValidate(),/P70_NAGASAKI_/);
ctx.GX_NAGASAKI_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxNagasakiSoilValidate(),true);
ctx.GX_NAGASAKI_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxNagasakiSoilValidate(),/P70_NAGASAKI_/);
const app=readFileSync('naft-app.html','utf8'),atlas=readFileSync('src/gx-data-explorer.js','utf8'),runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-nagasaki-soil.js'));
assert.ok(app.indexOf('src/gx-nagasaki-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxSagaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxNagasakiSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p70-nagasaki-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p70-nagasaki-soil-gis.test.mjs'));
console.log('NAFT_P70_NAGASAKI_863_POLYGONS_46_CODE_PAIRS_30_GUN_PAIRS_PASS');
