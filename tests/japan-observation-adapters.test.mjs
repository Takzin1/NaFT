import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {replayObservationSeries,observationAdapters} from '../scripts/lib/japan-observation-adapters.mjs';
import {replayFlux} from '../scripts/lib/japan-raw-flux.mjs';
let passed=0;
const ok=(v)=>{assert.ok(v);passed++;};
const eq=(v,w)=>{assert.equal(v,w);passed++;};
const bad=(fn,message)=>{assert.throws(fn,new RegExp(message));passed++;};
const BASE='research/japan-observation-adapters-2026-10-19/';
const get=(key)=>{
 const csv=readFileSync(BASE+key+'.csv'),manifest=JSON.parse(readFileSync(BASE+key+'.manifest.json','utf8'));
 return {csv,manifest};
};
const rewrite=(orig,edited,override={})=>{
 const csv=Buffer.from(edited,'utf8');
 return [csv,{...orig,csv_sha256:createHash('sha256').update(csv).digest('hex'),...override}];
};
const daily=get('daily'),eddy=get('eddy'),interval=get('interval');
ok(Object.keys(observationAdapters).length===5);
const d=replayObservationSeries(daily.csv,daily.manifest);
eq(d.coverage_status,'PARTIAL_OBSERVED');eq(d.observed_only_integral_mg_ch4_m2,'1.250000000');
eq(d.observed_only_integral_kg_ch4_ha,'0.012500000');
eq(d.full_window_total_mg_ch4_m2,null);eq(d.full_window_total_kg_ch4_ha,null);
eq(d.observed_seconds,'172800');eq(d.excluded_qc_seconds,'86400');
eq(d.unrepresented_gap_seconds,'0');eq(d.window_seconds,'259200');
eq(d.measured_coverage_percent,'66.666667');
eq(d.record_count,3);eq(d.accepted_rows,2);eq(d.excluded_rows,1);
ok(!d.gap_fill_applied&&!d.publisher_bytes_independently_attested);
ok(d.certified_tco2e===null&&d.uncertainty_interval===null&&d.causal_attribution===null);
const e=replayObservationSeries(eddy.csv,eddy.manifest);
eq(e.coverage_status,'COMPLETE_OBSERVED');eq(e.observed_only_integral_mg_ch4_m2,'0.144360000');
eq(e.observed_only_integral_kg_ch4_ha,'0.001443600');
eq(e.measured_coverage_percent,'100.000000');eq(e.full_window_total_mg_ch4_m2,e.observed_only_integral_mg_ch4_m2);
const i=replayObservationSeries(interval.csv,interval.manifest);
eq(i.coverage_status,'COMPLETE_OBSERVED');eq(i.observed_only_integral_mg_ch4_m2,'2.250000000');
const legacy='research/japan-field-raw-flux-2026-10-19/';
const v1=replayFlux(readFileSync(legacy+'synthetic-flux.csv'),JSON.parse(readFileSync(legacy+'synthetic-manifest.json','utf8')));
eq(i.observed_only_integral_mg_ch4_m2,v1.integrated_mg_ch4_m2);
eq(i.observed_only_integral_kg_ch4_ha,v1.integrated_kg_ch4_ha);
ok(!i.official_japan_factor_applicable&&!i.publisher_bytes_independently_attested);
bad(()=>replayObservationSeries(Buffer.concat([daily.csv,Buffer.from('x')]),daily.manifest),'OBS_SHA256');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,adapter_id:'EDDY_NMOL_CH4_M2_S_V1'}),'OBS_UNIT_OR_ADAPTER');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,gas:'N2O'}),'OBS_GAS_JURISDICTION');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,data_class:'ATTESTED_PUBLIC_DATA'}),'OBS_DATA_CLASS');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,original_publisher_bytes_verified:true}),'OBS_ATTESTATION');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,official_eligibility_verified:true}),'OBS_ATTESTATION');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,sampling_semantics:'INSTANTANEOUS_SAMPLE'}),'OBS_UNIT_OR_ADAPTER');
bad(()=>replayObservationSeries(daily.csv,{...daily.manifest,gap_fill_policy:'LINEAR'}),'OBS_GAS_JURISDICTION');
bad(()=>replayObservationSeries(eddy.csv,{...eddy.manifest,molar_mass_g_mol:'12'}),'OBS_MOLAR_MASS');
const asText=daily.csv.toString('utf8');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace(',,MISSING',',0.001000,MISSING'))),'OBS_EXCLUDED_ROW');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace('MISSING','IMPUTED_RESEARCH').replace(',,IMPUTED_RESEARCH',',0.001000,IMPUTED_RESEARCH'))),'OBS_EXCLUDED_ROW');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace('MISSING','UNKNOWN'))),'OBS_QC_UNKNOWN');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace('2026-06-03T00:00:00Z,2026-06-04T00:00:00Z,-0.000250','2026-06-03T12:00:00Z,2026-06-04T00:00:00Z,-0.000250'))),'OBS_DAILY_INTERVAL');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace('2026-06-03T00:00:00Z,2026-06-04T00:00:00Z','2026-06-02T23:00:00Z,2026-06-03T23:00:00Z'))),'OBS_OVERLAP');
bad(()=>replayObservationSeries(...rewrite(daily.manifest,asText.replace('0.001500','1000000'))),'OBS_INVALID_RATE');
bad(()=>replayObservationSeries(...rewrite(eddy.manifest,eddy.csv.toString().replace('2026-06-01T00:30:00Z,2026-06-01T01:00:00Z','2026-06-01T00:30:00Z,2026-06-01T02:00:00Z'),{observation_end_utc:'2026-06-01T02:00:00Z'})),'OBS_INTERVAL_INVALID');
const gapCsv=interval.csv.toString().replace('2026-06-02T00:00:00Z,2026-06-02T12:00:00Z','2026-06-02T02:00:00Z,2026-06-02T12:00:00Z');
const g=replayObservationSeries(...rewrite(interval.manifest,gapCsv));
eq(g.coverage_status,'PARTIAL_OBSERVED');eq(g.unrepresented_gap_seconds,'7200');
eq(g.full_window_total_mg_ch4_m2,null);
const emptyAll=daily.csv.toString().replace('0.001500,OBSERVED_GOOD',',MISSING').replace('-0.000250,OBSERVED_ACCEPTABLE',',MISSING');
const no=replayObservationSeries(...rewrite(daily.manifest,emptyAll));
eq(no.coverage_status,'NO_OBSERVATION');eq(no.observed_only_integral_mg_ch4_m2,null);
const imputed=replayObservationSeries(...rewrite(daily.manifest,asText.replace('MISSING','IMPUTED_RESEARCH')));
eq(imputed.research_imputed_rows_excluded,1);eq(imputed.observed_only_integral_mg_ch4_m2,'1.250000000');
console.log('JAPAN_OBSERVATION_ADAPTER_PASS: '+passed+' assertions (v1 parity, unit/QC/missing/attestation)');
