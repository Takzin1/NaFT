import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p36-ibaraki-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p36-ibaraki-soil-shapefile-v1');
assert.equal(g.source.source_zip_sha256,'af1bbf9d3c12eb51137e9ec8686f1255010eafa2e5424466a8d39b262d11a44f');
assert.equal(g.source.zip_bytes,16098958);
assert.equal(g.source.uncompressed_bytes,24405160);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((n,m)=>n+m.bytes,0),24405160);
assert.ok(g.source.members.every(m=>m.name.startsWith('k8茨城県.')&&/^[0-9a-f]{64}$/.test(m.sha256)));
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(g.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(g.geometry.shape_count,1335);
assert.equal(g.geometry.municipality_name_count,44);
assert.equal(g.geometry.unique_jcodes,44);
assert.equal(g.geometry.administrative_code_name_pairs,45);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.geometry.bounds_lon_lat,[139.69294608540187,35.74898638062405,140.8214158357868,36.933077667152084]);
assert.deepEqual(g.feature_counts_by_landuse,{'田':472,'普通畑':504,'牧草地':105,'樹園地':254});
assert.equal(g.soil_group_code_categories,13);
assert.equal(g.soil_fine_class_categories,51);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(g.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
const pairs=g.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,45);
assert.equal(new Set(pairs.map(r=>r[0])).size,44);
assert.equal(new Set(pairs.map(r=>r[1])).size,44);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,45);
assert.ok(pairs.every(r=>r.length===6&&/^08[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((n,r)=>n+r[2+i],0)),[472,504,105,254]);
assert.deepEqual(pairs.filter(r=>r[0]==='08211'),[['08211','守谷市',1,0,0,0],['08211','常総市',11,9,1,3]]);
assert.ok(pairs.some(r=>r[0]==='08224'&&r[1]==='守谷市'));
assert.equal(g.source_code_name_conflicts.length,2);
assert.equal(g.source_code_name_conflicts[0].resolution,'UNRESOLVED_ORIGINAL_KEPT');
const audit=spawnSync('python3',['scripts/p36-ibaraki-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const a=JSON.parse(audit.stdout);
assert.equal(a.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(a.raw_original_verified_in_ci,false);
const reject=spawnSync('python3',['scripts/p36-ibaraki-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(reject.status,0);
assert.match(reject.stderr,/P36_IBARAKI_SOURCE_BLOCKED:ZIP_SIZE/);
const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-ibaraki-soil.js','utf8'),box);
assert.equal(box.gxIbarakiSoilValidate(),true);
assert.equal(box.GX_IBARAKI_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_IBARAKI_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_IBARAKI_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxIbarakiSoilPanel('07'),'');
assert.equal(box.gxIbarakiSoilPanel('09'),'');
const html=box.gxIbarakiSoilPanel('08');
assert.match(html,/茨城県の農耕地土壌GIS/);
assert.match(html,/1,335/);
assert.match(html,/44市町村/);
assert.match(html,/45組合せ/);
assert.match(html,/08211/);
assert.match(html,/08224/);
assert.match(html,/要照合/);
assert.match(html,/守谷市/);
assert.match(html,/常総市/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,46);
box.GX_IBARAKI_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxIbarakiSoilValidate(),/P36_IBARAKI_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-ibaraki-soil.js')>0);
assert.ok(app.indexOf('src/gx-ibaraki-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxIbarakiSoilPanel(current.code)'));
for(const name of ['Hokkaido','Aomori','Iwate','Miyagi','Yamagata','Akita','Fukushima']){
 assert.ok(gx.includes('gx'+name+'SoilPanel(current.code)'));
}
