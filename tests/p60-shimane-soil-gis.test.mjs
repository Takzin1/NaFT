import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p60-shimane-soil-shapefile-source-v1.json','utf8'));
const hash='1c54bcdf1360103a856404e32bb6a31e5072ab35eb76b805b367ad8c500e0d90';
const expected={'田':350,'普通畑':309,'牧草地':81,'樹園地':187};
assert.equal(m.schema,'naft-p60-shimane-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,6246580);
assert.equal(m.source.members.length,7);
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,927);
assert.equal(m.geometry.unique_jcodes,20);
assert.equal(m.geometry.municipality_name_count,19);
assert.deepEqual(m.feature_counts_by_landuse,expected);
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,35);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,24);
assert.deepEqual(m.source_code_name_anomalies.foreign_prefecture_code_pairs,[['31202','安来市',1,0,0,0]]);
assert.equal(m.source_gun_quality.blank_gun_features,577);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{'美郷町':['邑智郡','飯石郡']});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p60-shimane-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,927);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const bad=spawnSync('python3',['scripts/p60-shimane-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(bad.status,0);
assert.match(bad.stderr,/P60_SHIMANE_SOURCE_BLOCKED:ZIP_SIZE/);
const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-shimane-soil.js','utf8'),context);
assert.equal(context.gxShimaneSoilValidate(),true);
assert.equal(context.GX_SHIMANE_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_SHIMANE_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_SHIMANE_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(context.gxShimaneSoilPanel('31'),'');
const html=context.gxShimaneSoilPanel('32');
for(const word of ['島根県の農耕地土壌GIS','927件','鳥取県系JCODE','飯石郡','35組合せ','24組合せ','要照合','農地面積ha'])assert.ok(html.includes(word),word);
context.GX_SHIMANE_CODE_PAIRS[0][2]++;
assert.throws(()=>context.gxShimaneSoilValidate(),/P60_SHIMANE_/);
context.GX_SHIMANE_CODE_PAIRS[0][2]--;
assert.equal(context.gxShimaneSoilValidate(),true);
context.GX_SHIMANE_GUN_PAIRS[0][2]++;
assert.throws(()=>context.gxShimaneSoilValidate(),/P60_SHIMANE_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-shimane-soil.js'));
assert.ok(app.indexOf('src/gx-shimane-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxTottoriSoilPanel(current.code)'));
assert.ok(atlas.includes('gxShimaneSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p60-shimane-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p60-shimane-soil-gis.test.mjs'));
console.log('NAFT_P60_SHIMANE_927_POLYGONS_35_JCODE_PAIRS_24_GUN_PAIRS_PASS');
