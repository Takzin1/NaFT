import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p50-shizuoka-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p50-shizuoka-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'静岡県.zip');
assert.equal(m.source.source_zip_sha256,'5f742daa989dac20ad00e0ab10a43ec7ee42a2f529a9b5f4fb20cb512b66b799');
assert.equal(m.source.zip_bytes,10405578);
assert.equal(m.source.uncompressed_bytes,16393570);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((s,r)=>s+r.bytes,0),16393570);
assert.ok(m.source.members.every(r=>r.name.startsWith('k17静岡県.')&&/^[0-9a-f]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,1376);
assert.deepEqual(m.geometry.bounds_lon_lat,[137.47834204518,34.59726879743675,139.1394105471396,35.43550077096272]);
assert.equal(m.geometry.municipality_name_count,43);
assert.equal(m.geometry.unique_jcodes,46);
assert.equal(m.geometry.administrative_code_name_pairs,104);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':1376});
assert.deepEqual(m.geometry.gun_counts,{'':1187,'南都留郡':1,'周智郡':30,'榛原郡':22,'田方郡':24,'賀茂郡':86,'足柄下郡':3,'駿東郡':23});
assert.deepEqual(m.feature_counts_by_landuse,{'田':412,'普通畑':451,'牧草地':44,'樹園地':469});
assert.equal(m.soil_group_code_categories,17);
assert.equal(m.soil_fine_class_categories,99);
assert.deepEqual(m.source_soil_completeness.missing_fields_counts,{'包括_統群':0,'統群コード':0,'亜群コード':0,'群コード':0});
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
const gunpairs=m.gun_name_pairs_counts_by_landuse;
const catTotals=rows=>[0,1,2,3].map(i=>rows.reduce((s,r)=>s+r[2+i],0));
assert.equal(pairs.length,104);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,104);
assert.equal(new Set(pairs.map(r=>r[0])).size,46);
assert.equal(new Set(pairs.map(r=>r[1])).size,43);
assert.deepEqual(catTotals(pairs),[412,451,44,469]);
assert.ok(pairs.every(r=>r.length===6&&/^(14|19|22)[0-9]{3}$/.test(r[0])));
const foreign=pairs.filter(r=>!r[0].startsWith('22'));
assert.equal(foreign.length,4);
assert.deepEqual(foreign,m.source_code_name_anomalies.foreign_prefecture_code_pairs);
assert.equal(foreign.reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0),4);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'14':3,'19':1});
assert.equal(Object.keys(m.source_code_name_anomalies.codes_with_multiple_names).length,28);
assert.equal(Object.keys(m.source_code_name_anomalies.names_with_multiple_codes).length,34);
assert.equal(m.source_code_name_anomalies.one_to_one_code_name_mapping,false);
assert.equal(m.source_code_name_anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

assert.equal(gunpairs.length,56);
assert.equal(new Set(gunpairs.map(r=>r[0]+'|'+r[1])).size,56);
assert.deepEqual(catTotals(gunpairs),[412,451,44,469]);
const gunMap=Object.fromEntries([...new Set(gunpairs.map(r=>r[0]))].map(g=>[g,gunpairs.filter(r=>r[0]===g).reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(gunMap,m.geometry.gun_counts);
assert.deepEqual(gunpairs.filter(r=>r[0]==='足柄下郡').map(r=>r[1]),['三島市','熱海市','裾野市']);
assert.deepEqual(gunpairs.find(r=>r[0]==='南都留郡'),['南都留郡','富士宮市',0,0,1,0]);
const blanks=m.source_gun_quality.empty_gun_name_pairs_with_nonempty_gun_elsewhere;
assert.equal(blanks.length,13);
assert.equal(blanks.reduce((s,r)=>s+r.empty_gun_polygon_count,0),137);
assert.equal(m.source_gun_quality.empty_gun_features_for_known_gun_towns,137);
assert.deepEqual(m.source_gun_quality.municipality_names_with_multiple_nonempty_guns,{});
assert.equal(m.source_gun_quality.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');

const audit=spawnSync('python3',['scripts/p50-shizuoka-soil-audit.py','audit'],{encoding:'utf8',timeout:12000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(JSON.parse(audit.stdout).raw_original_verified_in_ci,false);
const noOriginal=spawnSync('python3',['scripts/p50-shizuoka-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:12000});
assert.notEqual(noOriginal.status,0);
assert.match(noOriginal.stderr,/P50_SHIZUOKA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);

const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-shizuoka-soil.js','utf8'),ctx);
assert.equal(ctx.gxShizuokaSoilValidate(),true);
assert.equal(ctx.GX_SHIZUOKA_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_SHIZUOKA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_SHIZUOKA_GUN_NAME_PAIRS)),gunpairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(ctx.GX_SHIZUOKA_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(ctx.GX_SHIZUOKA_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(ctx.gxShizuokaSoilPanel('21'),'');
assert.equal(ctx.gxShizuokaSoilPanel('20'),'');
const html=ctx.gxShizuokaSoilPanel('22');
assert.match(html,/静岡県の農耕地土壌GIS/);
assert.match(html,/1,376件/);
assert.match(html,/104通り/);
assert.match(html,/56組合せ/);
assert.match(html,/神奈川県14系3/);
assert.match(html,/山梨県19系1/);
assert.match(html,/足柄下郡3/);
assert.match(html,/南都留郡1/);
assert.match(html,/137ポリゴン/);
