assert.match(html,/p51-aichi-soil-shapefile-source-v1.json/);
context.GX_AICHI_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>context.gxAichiSoilValidate(),/P51_AICHI_/);
context.GX_AICHI_CODE_NAME_PAIRS[0][2]--;
context.GX_AICHI_GUN_NAME_PAIRS.find(r=>r[0]==='下伊那郡'&&r[1]==='豊田市')[4]++;
assert.throws(()=>context.gxAichiSoilValidate(),/P51_AICHI_/);
