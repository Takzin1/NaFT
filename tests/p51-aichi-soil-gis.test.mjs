import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p51-aichi-soil-shapefile-source-v1.json','utf8'));
const hash='188614e4a0f369af4fb9470fd6a0af3d37bd5cfd5760c5b8170165d4d7f8d495';
assert.equal(m.schema,'naft-p51-aichi-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'愛知県.zip');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,9496674);
assert.equal(m.source.uncompressed_bytes,16068080);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((a,x)=>a+x.bytes,0),16068080);
assert.ok(m.source.members.every(x=>x.name.startsWith('k23愛知県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,2117);
assert.equal(m.geometry.municipality_name_count,64);
assert.equal(m.geometry.unique_jcodes,68);
assert.equal(m.geometry.administrative_code_name_pairs,174);
assert.deepEqual(m.geometry.bounds_lon_lat,[136.6739375580311,34.58256795306523,137.81151037495965,35.42157312729245]);
assert.deepEqual(m.geometry.sicho_counts,{'':2117});
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.gun_counts,{
  '':1697,'下伊那郡':2,'丹羽郡':52,'北設楽郡':87,'愛知郡':35,
  '海部郡':27,'知多郡':173,'西春日井郡':6,'額田郡':38
});
assert.equal(m.soil_group_code_categories,17);
assert.equal(m.soil_fine_class_categories,89);
assert.equal(m.soil_group_missing_features,0);
assert.equal(m.soil_detail_missing_features,0);
assert.deepEqual(m.feature_counts_by_landuse,{'田':845,'普通畑':798,'牧草地':77,'樹園地':397});

const codePairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(codePairs.length,174);
assert.equal(new Set(codePairs.map(r=>r[0]+'|'+r[1])).size,174);
assert.equal(new Set(codePairs.map(r=>r[0])).size,68);
assert.equal(new Set(codePairs.map(r=>r[1])).size,64);
assert.deepEqual([0,1,2,3].map(i=>codePairs.reduce((a,r)=>a+r[i+2],0)),[845,798,77,397]);
const anomalies=m.source_code_name_anomalies;
const foreign=codePairs.filter(r=>!r[0].startsWith('23'));
assert.equal(foreign.length,4);
assert.equal(foreign.reduce((a,r)=>a+r.slice(2).reduce((b,v)=>b+v,0),0),17);
assert.deepEqual(foreign,anomalies.foreign_prefecture_code_pairs);
assert.deepEqual(anomalies.foreign_code_prefix_totals,{'20':2,'21':4,'22':11});
assert.deepEqual(anomalies.foreign_prefixes,['20','21','22']);
assert.equal(Object.keys(anomalies.codes_with_multiple_names).length,44);
assert.equal(Object.keys(anomalies.names_with_multiple_codes).length,45);
assert.deepEqual(anomalies.historical_place_name_polygon_counts,{'長久手町':26});
assert.equal(anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
assert.equal(anomalies.one_to_one_code_name_mapping,false);

const gunPairs=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunPairs.length,80);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,80);
assert.deepEqual([0,1,2,3].map(i=>gunPairs.reduce((a,r)=>a+r[i+2],0)),[845,798,77,397]);
const counties=Object.fromEntries([...new Set(gunPairs.map(r=>r[0]))].map(g=>[g,gunPairs.filter(r=>r[0]===g).reduce((a,r)=>a+r.slice(2).reduce((b,v)=>b+v,0),0)]));
assert.deepEqual(counties,m.geometry.gun_counts);
assert.deepEqual(gunPairs.find(r=>r[0]==='下伊那郡'&&r[1]==='豊田市'),['下伊那郡','豊田市',0,0,2,0]);
const gunQuality=m.source_gun_quality;
assert.equal(gunQuality.empty_gun_features_for_names_with_county_elsewhere,238);
assert.equal(gunQuality.empty_gun_features_in_town_village_names,148);
assert.equal(gunQuality.empty_gun_name_pairs_with_nonempty_gun_elsewhere.reduce((a,r)=>a+r.empty_gun_polygon_count,0),238);
assert.equal(gunQuality.nonempty_gun_names_for_city[0].polygons,2);
assert.equal(gunQuality.nonempty_gun_names_for_city[0].gun,'下伊那郡');
assert.equal(gunQuality.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const audit=spawnSync('python3',['scripts/p51-aichi-soil-audit.py','audit'],{encoding:'utf8',timeout:20000});
assert.equal(audit.status,0,audit.stderr);
const result=JSON.parse(audit.stdout);
assert.equal(result.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(result.polygons,2117);
assert.equal(result.raw_original_verified_in_ci,false);
const bogus=spawnSync('python3',['scripts/p51-aichi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:20000});
assert.notEqual(bogus.status,0);
assert.match(bogus.stderr,/P51_AICHI_SOURCE_BLOCKED:ZIP_BYTES/);

const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-aichi-soil.js','utf8'),context);
assert.equal(context.gxAichiSoilValidate(),true);
assert.equal(context.GX_AICHI_SOURCE_HASH,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_AICHI_CODE_NAME_PAIRS)),codePairs);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_AICHI_GUN_NAME_PAIRS)),gunPairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_AICHI_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_AICHI_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(context.gxAichiSoilPanel('22'),'');
