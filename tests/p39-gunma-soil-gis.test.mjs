import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p39-gunma-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p39-gunma-soil-shapefile-v1');
assert.equal(g.source.source_zip_sha256,'b0e17480fb6e63a9d06282021bdf4cb9d8370d1d9609395b23ee475eed609596');
assert.equal(g.source.zip_bytes,9054377);
assert.equal(g.source.uncompressed_bytes,14540632);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((s,m)=>s+m.bytes,0),14540632);
assert.ok(g.source.members.every(m=>m.name.startsWith('k10群馬県.')&&/^[a-f0-9]{64}$/.test(m.sha256)));
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(g.geometry.shape_count,1331);
assert.equal(g.geometry.municipality_name_count,35);
assert.equal(g.geometry.unique_jcodes,38);
assert.equal(g.geometry.administrative_code_name_pairs,94);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.bounds_lon_lat,[138.39759594568946,36.062419709071186,139.65816954918944,36.86534968788782]);
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.feature_counts_by_landuse,{'田':411,'普通畑':554,'牧草地':62,'樹園地':304});
assert.equal(g.soil_group_code_categories,13);
assert.equal(g.soil_fine_class_categories,71);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(g.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
const pairs=g.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,94);
assert.equal(new Set(pairs.map(r=>r[0])).size,38);
assert.equal(new Set(pairs.map(r=>r[1])).size,35);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,94);
assert.ok(pairs.every(r=>r.length===6&&/^(09|10)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[i+2],0)),[411,554,62,304]);
const anomaly=g.source_code_name_anomalies;
const foreign=pairs.filter(r=>r[0].startsWith('09'));
assert.equal(foreign.length,6);
assert.equal(foreign.reduce((a,r)=>a+r.slice(2).reduce((x,y)=>x+y,0),0),24);
assert.deepEqual(foreign,anomaly.foreign_prefecture_code_pairs);
assert.deepEqual(anomaly.foreign_prefixes,['09']);
assert.deepEqual(anomaly.foreign_code_prefix_totals,{'09':24});
assert.equal(Object.keys(anomaly.codes_with_multiple_names).length,20);
assert.equal(Object.keys(anomaly.names_with_multiple_codes).length,30);
assert.equal(anomaly.one_to_one_code_name_mapping,false);
assert.equal(anomaly.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const audit=spawnSync('python3',['scripts/p39-gunma-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const result=JSON.parse(audit.stdout);
assert.equal(result.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(result.raw_original_verified_in_ci,false);
const rejected=spawnSync('python3',['scripts/p39-gunma-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(rejected.status,0);
assert.match(rejected.stderr,/P39_GUNMA_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-gunma-soil.js','utf8'),box);
assert.equal(box.gxGunmaSoilValidate(),true);
assert.equal(box.GX_GUNMA_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_GUNMA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_GUNMA_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxGunmaSoilPanel('09'),'');
assert.equal(box.gxGunmaSoilPanel('11'),'');
const html=box.gxGunmaSoilPanel('10');
assert.match(html,/群馬県の農耕地土壌GIS/);
assert.match(html,/1,331/);
assert.match(html,/35種類/);
assert.match(html,/94組合せ/);
assert.match(html,/24ポリゴン/);
assert.match(html,/栃木県/);
assert.match(html,/要照合/);
assert.match(html,/原本台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,95);
box.GX_GUNMA_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxGunmaSoilValidate(),/P39_GUNMA_CODE_NAME_ANOMALY/);
box.GX_GUNMA_CODE_NAME_PAIRS[0][2]--;
box.GX_GUNMA_CODE_NAME_PAIRS[6][2]++;
assert.throws(()=>box.gxGunmaSoilValidate(),/P39_GUNMA_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-gunma-soil.js')>0);
assert.ok(app.indexOf('src/gx-gunma-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxGunmaSoilPanel(current.code)'));
for(const name of ['Hokkaido','Aomori','Iwate','Miyagi','Yamagata','Akita','Fukushima','Ibaraki','Tochigi','Saitama']){
 assert.ok(gx.includes('gx'+name+'SoilPanel(current.code)'));
}
