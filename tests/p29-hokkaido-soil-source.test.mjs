import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const source=JSON.parse(readFileSync('research/p29-hokkaido-soil-shapefile-source-v1.json','utf8'));
assert.equal(source.schema,'naft-p29-hokkaido-agricultural-soil-polygon-source-v1');
assert.equal(source.geometry.shape_count,5477);
assert.equal(source.geometry.municipalities,186);
assert.equal(source.geometry.subprefectures,14);
assert.equal(source.source.original_shapefile_committed,false);
assert.equal(source.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(source.scientific_boundaries.official_credit_tco2e,null);
assert.deepEqual(source.geometry.bounds_lon_lat,[139.42536305675748,41.40803503361386,145.80253598026454,45.519946087378]);
assert.equal(source.source.members.find(x=>x.name.endsWith('.shp')).bytes,60339796);
assert.equal(source.source.members.find(x=>x.name.endsWith('.dbf')).bytes,6014100);
const p=spawnSync('python3',['scripts/p29-hokkaido-soil-audit.py','audit'],{encoding:'utf8',timeout:15000});
assert.equal(p.status,0,p.stderr);
assert.equal(JSON.parse(p.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const sandbox={gxEsc:(s)=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(sandbox);
vm.runInContext(readFileSync('src/gx-hokkaido-soil.js','utf8'),sandbox);
assert.equal(sandbox.gxHokkaidoSoilValidate(),true);
assert.equal(sandbox.GX_HOKKAIDO_SOIL_HASH,source.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(sandbox.GX_HOKKAIDO_SOIL_REGIONS)),source.subprefecture_feature_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(sandbox.GX_HOKKAIDO_SOIL_LANDUSE))),source.feature_counts_by_landuse);
assert.equal(sandbox.gxHokkaidoSoilPanel('07'),'');
const html=sandbox.gxHokkaidoSoilPanel('01');
assert.match(html,/北海道の農地土壌GIS/);
assert.match(html,/5,477/);
assert.match(html,/14振興局/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/元Shapefileの公開者・再配布ライセンス/);
assert.equal((html.match(/<tr>/g)||[]).length,15);
sandbox.GX_HOKKAIDO_SOIL_REGIONS[0][1]++;
assert.throws(()=>sandbox.gxHokkaidoSoilValidate(),/P29_HOKKAIDO_TOTAL/);
const page=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(page.indexOf('src/gx-hokkaido-soil.js')<page.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxHokkaidoSoilPanel(current.code)'));
console.log('NAFT_P29_HOKKAIDO_SOIL_SOURCE_AND_UI_PASS');
