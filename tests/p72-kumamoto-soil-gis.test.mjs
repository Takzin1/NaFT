import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p72-kumamoto-soil-shapefile-source-v1.json','utf8'));
const SHA='313aa016909916a4400d209c297120eb8b719e94264c8263c7671dbecccecb78';
assert.equal(m.schema,'naft-p72-kumamoto-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,SHA);
assert.equal(m.source.zip_bytes,12144480);
assert.equal(m.source.uncompressed_bytes,18977756);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1573);
assert.equal(m.geometry.municipality_name_count,45);
assert.equal(m.geometry.unique_jcodes,47);
assert.deepEqual(m.feature_counts_by_landuse,{'田':616,'普通畑':475,'牧草地':71,'樹園地':411});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,119);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,74);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'40':15});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,15);
assert.equal(m.source_gun_quality.blank_gun_features,779);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,132);
assert.equal(Object.keys(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name).length,6);
assert.equal(m.source_gun_quality.valid_kumamoto_gun_name_preserved,'芦北郡');
assert.equal(m.geometry.gun_counts['芦北郡'],56);
assert.equal(m.soil_group_code_categories,19);
assert.equal(m.soil_fine_class_categories,95);
assert.equal(m.soil_group_missing_features,0);
assert.equal(m.soil_detail_missing_features,0);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);

const run=spawnSync('python3',['scripts/p72-kumamoto-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(run.status,0,run.stderr);
assert.equal(JSON.parse(run.stdout).features,1573);
assert.equal(JSON.parse(run.stdout).private_zip_checked_in_ci,false);
const bad=spawnSync('python3',['scripts/p72-kumamoto-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(bad.status,0);
assert.match(bad.stderr,/P72_KUMAMOTO_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-kumamoto-soil.js','utf8'),ctx);
assert.equal(ctx.gxKumamotoSoilValidate(),true);
assert.equal(ctx.GX_KUMAMOTO_SOURCE_SHA,SHA);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KUMAMOTO_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KUMAMOTO_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxKumamotoSoilPanel('44'),'');
const html=ctx.gxKumamotoSoilPanel('43');
for(const term of ['熊本県の農耕地土壌GIS','1,573件','福岡県系JCODE','芦北郡','御船町','甲佐町','山都町','球磨村','益城町','西原村','119組合せ','74組合せ','要照合','農地面積ha'])assert.ok(html.includes(term),term);
ctx.GX_KUMAMOTO_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKumamotoSoilValidate(),/P72_KUMAMOTO_/);
ctx.GX_KUMAMOTO_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxKumamotoSoilValidate(),true);
ctx.GX_KUMAMOTO_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKumamotoSoilValidate(),/P72_KUMAMOTO_/);

const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-kumamoto-soil.js'));
assert.ok(app.indexOf('src/gx-kumamoto-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxOitaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxKumamotoSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p72-kumamoto-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p72-kumamoto-soil-gis.test.mjs'));
console.log('NAFT_P72_KUMAMOTO_1573_POLYGONS_119_CODE_PAIRS_74_GUN_PAIRS_PASS');
