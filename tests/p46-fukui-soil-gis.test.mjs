const m=JSON.parse(readFileSync('research/p46-fukui-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p46-fukui-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'福井県.zip');
assert.equal(m.source.source_zip_sha256,'4c81e96c9a94f48990cd4ba8ba14cf44ce9fced90321cb30ca65f0dbc2ec5357');
assert.equal(m.source.zip_bytes,3111309);
assert.equal(m.source.uncompressed_bytes,5089966);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((sum,x)=>sum+x.bytes,0),5089966);
assert.ok(m.source.members.every(x=>x.name.startsWith('k21福井県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
