assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_FUKUI_GUN))),gunCounts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(context.GX_FUKUI_LANDUSE))),m.feature_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_FUKUI_MISSING_GUN_NAMES)),q.empty_gun_name_pairs_with_nonempty_gun_elsewhere);
