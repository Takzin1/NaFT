assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,510);
assert.equal(m.geometry.municipality_name_count,17);
assert.equal(m.geometry.unique_jcodes,18);
assert.equal(m.geometry.administrative_code_name_pairs,31);
assert.deepEqual(m.geometry.bounds_lon_lat,[135.45436972693855,35.38873158534855,136.69095552335563,36.288086622838335]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':510});
assert.deepEqual(m.geometry.gun_counts,{'':333,'三方上中郡':30,'三方郡':32,'丹生郡':26,'今立郡':17,'南条郡':18,'吉田郡':20,'大飯郡':34});
assert.deepEqual(m.feature_counts_by_landuse,{'田':265,'普通畑':159,'牧草地':19,'樹園地':67});
assert.equal(m.soil_group_code_categories,16);
assert.equal(m.soil_fine_class_categories,48);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.gun_name_missingness_detected,true);
assert.equal(m.scientific_boundaries.gun_name_variation_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
const sum=xs=>xs.reduce((a,b)=>a+b,0);
assert.equal(pairs.length,31);
assert.equal(new Set(pairs.map(x=>x[0])).size,18);
assert.equal(new Set(pairs.map(x=>x[1])).size,17);
assert.equal(new Set(pairs.map(x=>x[0]+'|'+x[1])).size,31);
assert.deepEqual([0,1,2,3].map(i=>sum(pairs.map(r=>r[i+2]))),[265,159,19,67]);
assert.ok(pairs.every(r=>r.length===6&&/^(17|18)[0-9]{3}$/.test(r[0])));
const anomaly=m.source_code_name_anomalies;
assert.deepEqual(pairs.filter(r=>r[0].startsWith('17')),[['17206','あわら市',0,0,0,1]]);
assert.deepEqual(anomaly.foreign_prefecture_code_pairs,[['17206','あわら市',0,0,0,1]]);
assert.equal(anomaly.foreign_prefecture_code_feature_count,1);
assert.deepEqual(anomaly.foreign_code_prefix_totals,{'17':1});
assert.equal(Object.keys(anomaly.codes_with_multiple_names).length,8);
assert.equal(Object.keys(anomaly.names_with_multiple_codes).length,9);
assert.equal(anomaly.one_to_one_code_name_mapping,false);
assert.equal(anomaly.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const gunPairs=m.gun_name_pairs_counts_by_landuse;
const gunCounts=m.geometry.gun_counts;
assert.equal(gunPairs.length,22);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,22);
assert.deepEqual([0,1,2,3].map(i=>sum(gunPairs.map(r=>r[i+2]))),[265,159,19,67]);
for(const [gun,count] of Object.entries(gunCounts))
 assert.equal(gunPairs.filter(r=>r[0]===gun).reduce((s,r)=>s+sum(r.slice(2)),0),count);
assert.deepEqual(gunPairs.find(r=>r[0]==='三方郡'&&r[1]==='若狭町'),['三方郡','若狭町',1,0,0,1]);
assert.deepEqual(gunPairs.find(r=>r[0]==='三方上中郡'&&r[1]==='若狭町'),['三方上中郡','若狭町',13,7,1,9]);
const q=m.source_gun_quality;
assert.equal(q.empty_gun_features_for_known_gun_towns,20);
assert.equal(q.empty_gun_name_pairs_with_nonempty_gun_elsewhere.length,4);
assert.deepEqual(Object.fromEntries(q.empty_gun_name_pairs_with_nonempty_gun_elsewhere.map(x=>[x.municipality_name,x.empty_gun_polygon_count])),{'南越前町':3,'永平寺町':8,'若狭町':3,'越前町':6});
assert.equal(q.wakasa_sanpo_gun_feature_count,2);
assert.deepEqual(q.wakasa_sanpo_gun_landuse,{'田':1,'普通畑':0,'牧草地':0,'樹園地':1});
assert.equal(q.status,'SOURCE_GUN_VARIATION_KEPT_NO_GUN_JOIN');

