const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-fukui-soil.js','utf8'),context);
assert.equal(context.gxFukuiSoilValidate(),true);
assert.equal(context.GX_FUKUI_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_FUKUI_CODE_NAME_PAIRS)),pairs);
