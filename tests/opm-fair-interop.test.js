'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
for(const name of ['mrv-core','methodology-packs','mrv-compiler','compiler-demo','opm-fair-interop']) {
  vm.runInThisContext(fs.readFileSync('src/'+name+'.js','utf8'),{filename:name+'.js'});
}
const input=syntheticClaim('OPM-FAIR-1');
const pack=COMPILER_REGISTRY['NAFT-SYNTHETIC@1'];
const pkg=compileEvidence(input,pack);
const before=canonicalize(pkg);
const a=naftOpmCrosswalk(pkg,input,pack);
const b=naftOpmCrosswalk(pkg,JSON.parse(JSON.stringify(input)),pack);
assert.deepEqual(a,b,'repeatable crosswalk');
assert.equal(naftValidateOpmCrosswalk(a),true);
assert.equal(a.source_edge_direction,'dependency_to_dependent');
assert.equal(a.edge_direction,'effect_to_cause');
assert.ok(a.edges.some(e=>e.relation==='used'&&e.role==='evidence'));
assert.ok(a.edges.some(e=>e.relation==='wasGeneratedBy'&&e.role==='compiled_package'));
assert.ok(a.nodes.every(n=>n.kind==='artifact'||n.kind==='process'));
assert.equal(a.full_opm_conformance_asserted,false);
assert.equal(a.certified_tco2e,null);
assert.equal(canonicalize(pkg),before,'existing package unchanged');
const tampered=JSON.parse(JSON.stringify(pkg));tampered.package_hash='0'.repeat(64);
assert.throws(()=>naftOpmCrosswalk(tampered,input,pack),/NAFT_RESEARCH_STALE_COMPILER_PACKAGE/);
const wrong=JSON.parse(JSON.stringify(input));wrong.field.area_ha=999;
assert.throws(()=>naftOpmCrosswalk(pkg,wrong,pack),/NAFT_RESEARCH_STALE_COMPILER_PACKAGE/);
const unsafe=JSON.parse(JSON.stringify(a));unsafe.edges[0].relation='wasControlledBy';
assert.throws(()=>naftValidateOpmCrosswalk(unsafe),/NAFT_RESEARCH_OPM_EDGE_TYPE_OR_DIRECTION/);
const noRole=JSON.parse(JSON.stringify(a));delete noRole.edges[0].role;
assert.throws(()=>naftValidateOpmCrosswalk(noRole),/NAFT_RESEARCH_OPM_EDGE_ROLE/);
const reversed=JSON.parse(JSON.stringify(a));
const tmp=reversed.edges[0].from;reversed.edges[0].from=reversed.edges[0].to;reversed.edges[0].to=tmp;
assert.throws(()=>naftValidateOpmCrosswalk(reversed),/NAFT_RESEARCH_OPM_EDGE_TYPE_OR_DIRECTION/);
const cycle=JSON.parse(JSON.stringify(a));
const process=cycle.nodes.find(n=>n.kind==='process');
const artifact=cycle.nodes.find(n=>n.kind==='artifact'&&n.attributes.source_type!=='compiler_package');
cycle.edges.push({from:artifact.id,to:process.id,relation:'wasGeneratedBy',role:'malicious'});
assert.throws(()=>naftValidateOpmCrosswalk(cycle),/NAFT_RESEARCH_OPM_CYCLE/);
const direct=naftFairPackageMetadata(pkg,input,pack);
assert.equal(direct.persistent_identifier,null);
assert.equal(direct.license_uri,null);
assert.equal(direct.rights_review_status,'UNKNOWN');
assert.equal(direct.formal_certification,false);
assert.equal(direct.certified_tco2e,null);
const check=naftFairSelfCheck(direct);
const status=id=>check.checks.find(x=>x.principle===id).status;
assert.equal(check.checks.length,15);
assert.equal(status('F1'),'MISSING_OR_UNESTABLISHED');
assert.equal(status('R1.1'),'MISSING_OR_UNESTABLISHED');
assert.equal(status('R1.2'),'DECLARED_UNVERIFIED');
assert.equal(check.fair_certified,false);
assert.equal(check.redistribution_authorized,'NOT_ESTABLISHED');
const decorated=JSON.parse(JSON.stringify(direct));
decorated.persistent_identifier='https://doi.org/10.1234/example';
decorated.metadata_access_url='https://example.test/metadata';
decorated.access_url='https://example.test/data';
decorated.license_uri='https://creativecommons.org/licenses/by/4.0/';
decorated.rights_review_status='REVIEWED';
decorated.indexed_in='https://example.test/index';
decorated.access_policy='login_optional';
decorated.metadata_retention_policy='Retain metadata independently';
decorated.schema_uri='https://example.test/schema';
decorated.vocabulary_uris=['https://example.test/vocab'];
decorated.community_standard_uri='https://example.test/domain';
const checked=naftFairSelfCheck(decorated);
assert.ok(checked.checks.every(x=>x.status==='DECLARED_UNVERIFIED'));
assert.equal(checked.fair_certified,false,'self-declaration cannot prove compliance');
assert.equal(checked.external_endpoints_checked,false);
assert.equal(checked.redistribution_authorized,'REQUIRES_MANUAL_CONFIRMATION');
const receipt=naftResearchInteropReceipt(pkg,input,pack);
assert.equal(receipt.certification,'NOT_PERFORMED');
assert.equal(receipt.on_chain_status,'NOT_SUBMITTED');
assert.equal(receipt.opm.crosswalk_hash,a.crosswalk_hash);
const registry=JSON.parse(fs.readFileSync('research/literature-2026-11-08/opm-fair-sources.json','utf8'));
assert.equal(registry.work_count,2);
assert.equal(registry.local_pdf_versions.length,3);
assert.equal(new Set(registry.local_pdf_versions.map(x=>x.work_id)).size,2);
assert.ok(registry.local_pdf_versions.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)&&x.redistribute_pdf===false));
assert.equal(registry.rights_review_complete,false);
console.log('OPM_FAIR_INTEROP_PASS: direction, roles, DAG, reproducibility, stale rejection, FAIR rights gate');
