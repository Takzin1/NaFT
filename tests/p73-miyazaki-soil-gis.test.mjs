import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p73-miyazaki-soil-shapefile-source-v1.json','utf8'));
const SHA='2d2bd2bf4a29927698cc550c04850b850dd3aa5cf3f8ab357af2f6ad08024f51';
assert.equal(m.schema,'naft-p73-miyazaki-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,SHA);
assert.equal(m.source.zip_bytes,10600644);
assert.equal(m.source.uncompressed_bytes,16035814);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,756);
assert.equal(m.geometry.municipality_name_count,26);
assert.equal(m.geometry.unique_jcodes,27);
assert.deepEqual(m.feature_counts_by_landuse,{'田':297,'普通畑':249,'牧草地':58,'樹園地':152});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,53);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,36);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'43':4});
assert.deepEqual(m.source_code_name_anomalies.foreign_prefecture_code_pairs,[['43428','高千穂町',2,1,1,0]]);
assert.equal(m.source_gun_quality.blank_gun_features,438);
assert.equal(m.source_gun_quality.non_miyazaki_gun_name_feature_count,4);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,57);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{'高千穂町':['西臼杵郡','阿蘇郡']});
assert.equal(m.soil_group_code_categories,14);
assert.equal(m.soil_fine_class_categories,68);
assert.equal(m.soil_group_missing_features,0);
assert.equal(m.soil_detail_missing_features,0);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p73-miyazaki-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,756);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p73-miyazaki-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P73_MIYAZAKI_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-miyazaki-soil.js','utf8'),ctx);
assert.equal(ctx.gxMiyazakiSoilValidate(),true);
assert.equal(ctx.GX_MIYAZAKI_SOURCE_SHA,SHA);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_MIYAZAKI_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_MIYAZAKI_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxMiyazakiSoilPanel('43'),'');
const html=ctx.gxMiyazakiSoilPanel('45');
for(const term of ['宮崎県の農耕地土壌GIS','756件','熊本県系JCODE','43428','高千穂町','阿蘇郡','西臼杵郡','53組合せ','36組合せ','要照合','農地面積ha'])assert.ok(html.includes(term),term);
ctx.GX_MIYAZAKI_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxMiyazakiSoilValidate(),/P73_MIYAZAKI_/);
ctx.GX_MIYAZAKI_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxMiyazakiSoilValidate(),true);
ctx.GX_MIYAZAKI_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxMiyazakiSoilValidate(),/P73_MIYAZAKI_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-miyazaki-soil.js'));
assert.ok(app.indexOf('src/gx-miyazaki-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxKumamotoSoilPanel(current.code)'));
assert.ok(atlas.includes('gxMiyazakiSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p73-miyazaki-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p73-miyazaki-soil-gis.test.mjs'));
console.log('NAFT_P73_MIYAZAKI_756_POLYGONS_53_JCODE_PAIRS_36_GUN_PAIRS_PASS');
