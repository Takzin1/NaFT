import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p66-ehime-soil-shapefile-source-v1.json','utf8'));
const hash='3af0a956b989b9eaac0746695e6bc9930dab6267a62061a3aca84aa6bceecbbc';
assert.equal(m.schema,'naft-p66-ehime-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,13466351);
assert.equal(m.source.uncompressed_bytes,19995760);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,629);
assert.equal(m.geometry.municipality_name_count,20);
assert.equal(m.geometry.unique_jcodes,21);
assert.deepEqual(m.feature_counts_by_landuse,{'田':219,'普通畑':189,'牧草地':14,'樹園地':207});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,37);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,25);
assert.deepEqual(m.source_code_name_anomalies.foreign_prefecture_code_pairs,[['36208','四国中央市',0,0,0,1]]);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'36':1});
assert.equal(m.source_gun_quality.blank_gun_features,454);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,29);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p66-ehime-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,629);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p66-ehime-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P66_EHIME_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-ehime-soil.js','utf8'),ctx);
assert.equal(ctx.gxEhimeSoilValidate(),true);
assert.equal(ctx.GX_EHIME_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_EHIME_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_EHIME_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxEhimeSoilPanel('37'),'');
const html=ctx.gxEhimeSoilPanel('38');
for(const s of ['愛媛県の農耕地土壌GIS','629件','徳島県系JCODE','37組合せ','25組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
ctx.GX_EHIME_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxEhimeSoilValidate(),/P66_EHIME_/);
ctx.GX_EHIME_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxEhimeSoilValidate(),true);
ctx.GX_EHIME_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxEhimeSoilValidate(),/P66_EHIME_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-ehime-soil.js'));
assert.ok(app.indexOf('src/gx-ehime-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxKagawaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxEhimeSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p66-ehime-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p66-ehime-soil-gis.test.mjs'));
console.log('NAFT_P66_EHIME_629_POLYGONS_37_JCODE_PAIRS_25_GUN_PAIRS_PASS');
