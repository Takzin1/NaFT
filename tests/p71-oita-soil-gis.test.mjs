import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p71-oita-soil-shapefile-source-v1.json','utf8'));
const hash='8bc9152a0d50d6e3dcdea6eb1ecc304b386ddafe1de4af1575ebde4f5aa70965';
assert.equal(m.schema,'naft-p71-oita-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,7647021);
assert.equal(m.source.uncompressed_bytes,11782322);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,820);
assert.equal(m.geometry.municipality_name_count,18);
assert.equal(m.geometry.unique_jcodes,27);
assert.deepEqual(m.feature_counts_by_landuse,{'田':311,'普通畑':234,'牧草地':80,'樹園地':195});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,52);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,27);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'40':6,'43':17});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,23);
assert.equal(m.source_gun_quality.blank_gun_features,689);
assert.equal(m.source_gun_quality.non_oita_gun_name_feature_count,19);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,168);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{
  '日田市':['朝倉郡','阿蘇郡'],'九重町':['玖珠郡','阿蘇郡'],'玖珠町':['玖珠郡','阿蘇郡']});
assert.equal(m.soil_group_code_categories,15);
assert.equal(m.soil_fine_class_categories,53);
assert.equal(m.soil_group_missing_features,0);
assert.equal(m.soil_detail_missing_features,0);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const result=spawnSync('python3',['scripts/p71-oita-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(result.status,0,result.stderr);
assert.equal(JSON.parse(result.stdout).features,820);
assert.equal(JSON.parse(result.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p71-oita-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P71_OITA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-oita-soil.js','utf8'),ctx);
assert.equal(ctx.gxOitaSoilValidate(),true);
assert.equal(ctx.GX_OITA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_OITA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_OITA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxOitaSoilPanel('42'),'');
const html=ctx.gxOitaSoilPanel('44');
for(const x of ['大分県の農耕地土壌GIS','820件','福岡県系JCODE','熊本県系JCODE','阿蘇郡','朝倉郡','築上郡','九重町','玖珠町','日田市','52組合せ','27組合せ','要照合','農地面積ha'])assert.ok(html.includes(x),x);
ctx.GX_OITA_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxOitaSoilValidate(),/P71_OITA_/);
ctx.GX_OITA_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxOitaSoilValidate(),true);
ctx.GX_OITA_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxOitaSoilValidate(),/P71_OITA_/);
const app=readFileSync('naft-app.html','utf8'),atlas=readFileSync('src/gx-data-explorer.js','utf8'),runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-oita-soil.js'));
assert.ok(app.indexOf('src/gx-oita-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxNagasakiSoilPanel(current.code)'));
assert.ok(atlas.includes('gxOitaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p71-oita-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p71-oita-soil-gis.test.mjs'));
