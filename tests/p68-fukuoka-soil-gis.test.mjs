import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p68-fukuoka-soil-shapefile-source-v1.json','utf8'));
const hash='dfce591f4f8b9758cbf0520245ff419011678cf57d38b1f82375b96485f1a276';
assert.equal(m.schema,'naft-p68-fukuoka-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,10282149);
assert.equal(m.source.uncompressed_bytes,16543070);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(x=>/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1706);
assert.equal(m.geometry.municipality_name_count,70);
assert.equal(m.geometry.unique_jcodes,70);
assert.deepEqual(m.feature_counts_by_landuse,{'田':758,'普通畑':544,'牧草地':50,'樹園地':354});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,163);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,99);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,0);
assert.equal(m.source_gun_quality.blank_gun_features,1138);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,169);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{
  '大刀洗町':['三井郡','朝倉郡'],'築上町':['京都郡','築上郡'],'鞍手町':['遠賀郡','鞍手郡']});
assert.equal(m.historical_admin_warnings.source_has_nakagawa_machi,true);
assert.equal(m.historical_admin_warnings.joined_to_current_municipalities,false);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const publicAudit=spawnSync('python3',['scripts/p68-fukuoka-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(publicAudit.status,0,publicAudit.stderr);
assert.equal(JSON.parse(publicAudit.stdout).features,1706);
assert.equal(JSON.parse(publicAudit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p68-fukuoka-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P68_FUKUOKA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);

const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-fukuoka-soil.js','utf8'),ctx);
assert.equal(ctx.gxFukuokaSoilValidate(),true);
assert.equal(ctx.GX_FUKUOKA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_FUKUOKA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_FUKUOKA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxFukuokaSoilPanel('39'),'');
const html=ctx.gxFukuokaSoilPanel('40');
for(const word of ['福岡県の農耕地土壌GIS','1,706件','那珂川町','三瀦郡','筑紫郡','大刀洗町','築上町','鞍手町','163組合せ','99組合せ','要照合','農地面積ha'])assert.ok(html.includes(word),word);
ctx.GX_FUKUOKA_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxFukuokaSoilValidate(),/P68_FUKUOKA_/);
ctx.GX_FUKUOKA_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxFukuokaSoilValidate(),true);
ctx.GX_FUKUOKA_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxFukuokaSoilValidate(),/P68_FUKUOKA_/);

const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-fukuoka-soil.js'));
assert.ok(app.indexOf('src/gx-fukuoka-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxKochiSoilPanel(current.code)'));
assert.ok(atlas.includes('gxFukuokaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p68-fukuoka-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p68-fukuoka-soil-gis.test.mjs'));
console.log('NAFT_P68_FUKUOKA_1706_POLYGONS_163_CODE_PAIRS_99_GUN_PAIRS_PASS');
