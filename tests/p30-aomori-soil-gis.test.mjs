import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p30-aomori-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p30-aomori-soil-shapefile-v1');
assert.equal(g.source.zip_bytes,9300558);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((sum,x)=>sum+x.bytes,0),14669992);
assert.match(g.source.source_zip_sha256,/^[a-f0-9]{64}$/);
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.geometry.shape_count,1311);
assert.equal(g.geometry.municipalities,40);
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.geometry.bounds_lon_lat,[139.86400637479457,40.22964860695858,141.78650607401556,41.54065286776461]);
assert.equal(g.feature_counts_by_landuse['田'],457);
assert.equal(g.feature_counts_by_landuse['普通畑'],394);
assert.equal(g.feature_counts_by_landuse['牧草地'],180);
assert.equal(g.feature_counts_by_landuse['樹園地'],280);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.soil_group_code_categories,19);
assert.equal(g.soil_fine_class_categories,69);
assert.equal(g.municipalities_counts_by_landuse.length,40);
const audit=spawnSync('python3',['scripts/p30-aomori-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const missing=spawnSync('python3',['scripts/p30-aomori-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(missing.status,0);
assert.match(missing.stderr,/P30_AOMORI_SOURCE_BLOCKED:ZIP_SIZE/);
const box={gxEsc:(s)=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-aomori-soil.js','utf8'),box);
assert.equal(box.gxAomoriSoilValidate(),true);
assert.equal(box.GX_AOMORI_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_AOMORI_MUNICIPALITIES)),g.municipalities_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_AOMORI_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxAomoriSoilPanel('01'),'');
const html=box.gxAomoriSoilPanel('02');
assert.match(html,/青森県の農耕地土壌GIS/);
assert.match(html,/1,311/);
assert.match(html,/40市町村/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,41);
box.GX_AOMORI_MUNICIPALITIES[0][2]++;
assert.throws(()=>box.gxAomoriSoilValidate(),/P30_AOMORI_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-aomori-soil.js')>0);
assert.ok(app.indexOf('src/gx-aomori-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxAomoriSoilPanel(current.code)'));
console.log('NAFT_P30_AOMORI_SOIL_GIS_INTAKE_AND_UI_PASS');
