import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const reg=JSON.parse(readFileSync('research/p33-yamagata-soil-shapefile-source-v1.json','utf8'));
assert.equal(reg.schema,'naft-p33-yamagata-soil-shapefile-v1');
assert.equal(reg.source.zip_bytes,10756335);
assert.equal(reg.source.uncompressed_bytes,17175180);
assert.equal(reg.source.source_zip_sha256,'ec2890ef0329b30054159a8a85ba731027d13f952f5ec1c849c36a38d4ec7e2c');
assert.equal(reg.source.members.length,7);
assert.equal(reg.source.members.reduce((s,m)=>s+m.bytes,0),17175180);
assert.ok(reg.source.members.every(m=>/^[a-f0-9]{64}$/.test(m.sha256)));
assert.equal(reg.source.original_zip_committed,false);
assert.equal(reg.source.raw_geometry_committed,false);
assert.equal(reg.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(reg.geometry.shape_count,1651);
assert.equal(reg.geometry.municipalities,35);
assert.deepEqual(reg.geometry.sicho_unique_values,['']);
assert.equal(reg.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(reg.geometry.bounds_lon_lat,[139.5489311470065,37.79515834071243,140.62155752318338,39.10712316809213]);
assert.deepEqual(reg.feature_counts_by_landuse,{'田':618,'普通畑':500,'牧草地':138,'樹園地':395});
assert.equal(reg.soil_group_code_categories,18);
assert.equal(reg.soil_fine_class_categories,93);
assert.equal(reg.scientific_boundaries.official_credit_tco2e,null);
assert.equal(reg.scientific_boundaries.raw_geometry_licensed_for_publication,false);
assert.equal(reg.municipalities_counts_by_landuse.length,35);
assert.equal(new Set(reg.municipalities_counts_by_landuse.map(row=>row[0])).size,35);
assert.ok(reg.municipalities_counts_by_landuse.every(row=>/^06[0-9]{3}$/.test(row[0])));
assert.deepEqual([0,1,2,3].map(i=>reg.municipalities_counts_by_landuse.reduce((s,row)=>s+row[i+2],0)),[618,500,138,395]);

const status=spawnSync('python3',['scripts/p33-yamagata-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(status.status,0,status.stderr);
assert.equal(JSON.parse(status.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const bad=spawnSync('python3',['scripts/p33-yamagata-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(bad.status,0);
assert.match(bad.stderr,/P33_YAMAGATA_SOURCE_BLOCKED:ZIP_SIZE/);
const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-yamagata-soil.js','utf8'),box);
assert.equal(box.gxYamagataSoilValidate(),true);
assert.equal(box.GX_YAMAGATA_SOURCE_HASH,reg.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_YAMAGATA_MUNICIPALITIES)),reg.municipalities_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_YAMAGATA_LANDUSE))),reg.feature_counts_by_landuse);
assert.equal(box.gxYamagataSoilPanel('01'),'');
assert.equal(box.gxYamagataSoilPanel('04'),'');
const html=box.gxYamagataSoilPanel('06');
assert.match(html,/山形県の農耕地土壌GIS/);
assert.match(html,/1,651/);
assert.match(html,/35市町村/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,36);
box.GX_YAMAGATA_MUNICIPALITIES[0][2]++;
assert.throws(()=>box.gxYamagataSoilValidate(),/P33_YAMAGATA_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-yamagata-soil.js')>0);
assert.ok(app.indexOf('src/gx-yamagata-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxYamagataSoilPanel(current.code)'));
assert.ok(gx.includes('gxHokkaidoSoilPanel(current.code)'));
assert.ok(gx.includes('gxAomoriSoilPanel(current.code)'));
assert.ok(gx.includes('gxIwateSoilPanel(current.code)'));
assert.ok(gx.includes('gxMiyagiSoilPanel(current.code)'));
console.log('NAFT_P33_YAMAGATA_SOIL_GIS_INTAKE_AND_UI_PASS');
