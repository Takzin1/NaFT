import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p31-iwate-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p31-iwate-soil-shapefile-v1');
assert.equal(g.source.zip_bytes,15089311);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((sum,x)=>sum+x.bytes,0),23795048);
assert.match(g.source.source_zip_sha256,/^[a-f0-9]{64}$/);
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.geometry.shape_count,2149);
assert.equal(g.geometry.municipalities,33);
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.geometry.bounds_lon_lat,[140.71055549154266,38.72421929402586,142.0391644869843,40.44934932676321]);
assert.equal(g.feature_counts_by_landuse['田'],726);
assert.equal(g.feature_counts_by_landuse['普通畑'],641);
assert.equal(g.feature_counts_by_landuse['牧草地'],415);
assert.equal(g.feature_counts_by_landuse['樹園地'],367);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.soil_group_code_categories,17);
assert.equal(g.soil_fine_class_categories,85);
assert.deepEqual(g.historical_place_names_as_source,['滝沢村']);
assert.ok(g.municipalities_counts_by_landuse.some(row=>row[0]==='03305'&&row[1]==='滝沢村'));
assert.equal(new Set(g.municipalities_counts_by_landuse.map(row=>row[0])).size,33);
assert.equal(g.municipalities_counts_by_landuse.length,33);
const audit=spawnSync('python3',['scripts/p31-iwate-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const missing=spawnSync('python3',['scripts/p31-iwate-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(missing.status,0);
assert.match(missing.stderr,/P31_IWATE_SOURCE_BLOCKED:ZIP_SIZE/);
const box={gxEsc:(s)=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-iwate-soil.js','utf8'),box);
assert.equal(box.gxIwateSoilValidate(),true);
assert.equal(box.GX_IWATE_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_IWATE_MUNICIPALITIES)),g.municipalities_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_IWATE_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxIwateSoilPanel('01'),'');
const html=box.gxIwateSoilPanel('03');
assert.match(html,/岩手県の農耕地土壌GIS/);
assert.match(html,/2,149/);
assert.match(html,/33市町村/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/滝沢村/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,34);
box.GX_IWATE_MUNICIPALITIES[0][2]++;
assert.throws(()=>box.gxIwateSoilValidate(),/P31_IWATE_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-iwate-soil.js')>0);
assert.ok(app.indexOf('src/gx-iwate-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxIwateSoilPanel(current.code)'));
console.log('NAFT_P31_IWATE_SOIL_GIS_INTAKE_AND_UI_PASS');
