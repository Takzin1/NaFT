import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p38-saitama-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p38-saitama-soil-shapefile-v1');
assert.equal(g.source.source_zip_sha256,'6472a9e2fc0aa25c23e08b3593d9c8bc1135db7e22dd09c8083eb865923ed474');
assert.equal(g.source.zip_bytes,8008925);
assert.equal(g.source.uncompressed_bytes,13692638);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((n,m)=>n+m.bytes,0),13692638);
assert.ok(g.source.members.every(m=>m.name.startsWith('k11埼玉県.')&&/^[0-9a-f]{64}$/.test(m.sha256)));
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(g.geometry.shape_count,1912);
assert.equal(g.geometry.municipality_name_count,73);
assert.equal(g.geometry.unique_jcodes,81);
assert.equal(g.geometry.administrative_code_name_pairs,215);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.bounds_lon_lat,[138.8680488573203,35.763381944347785,139.8954271704511,36.27829900000003]);
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.feature_counts_by_landuse,{'田':673,'普通畑':830,'牧草地':24,'樹園地':385});
assert.equal(g.soil_group_code_categories,15);
assert.equal(g.soil_fine_class_categories,64);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(g.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
const pairs=g.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,215);
assert.equal(new Set(pairs.map(r=>r[0])).size,81);
assert.equal(new Set(pairs.map(r=>r[1])).size,73);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,215);
assert.ok(pairs.every(r=>r.length===6&&/^(08|09|10|11)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[i+2],0)),[673,830,24,385]);
const anomalies=g.source_code_name_anomalies;
const foreign=pairs.filter(r=>!r[0].startsWith('11'));
assert.equal(foreign.length,10);
assert.equal(foreign.reduce((a,r)=>a+r.slice(2).reduce((x,y)=>x+y,0),0),17);
assert.deepEqual(foreign,anomalies.foreign_prefecture_code_pairs);
assert.deepEqual(anomalies.foreign_code_prefix_totals,{'08':2,'09':3,'10':12});
assert.deepEqual(anomalies.foreign_prefixes,['08','09','10']);
assert.equal(Object.keys(anomalies.codes_with_multiple_names).length,54);
assert.equal(Object.keys(anomalies.names_with_multiple_codes).length,64);
assert.deepEqual(anomalies.historical_place_names_as_source,['白岡町','鳩ヶ谷市']);
assert.deepEqual(anomalies.historical_place_name_polygon_counts,{'白岡町':56,'鳩ヶ谷市':5});
assert.equal(anomalies.one_to_one_code_name_mapping,false);
assert.equal(anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const audit=spawnSync('python3',['scripts/p38-saitama-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const outcome=JSON.parse(audit.stdout);
assert.equal(outcome.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(outcome.raw_original_verified_in_ci,false);
const wrong=spawnSync('python3',['scripts/p38-saitama-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(wrong.status,0);
assert.match(wrong.stderr,/P38_SAITAMA_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-saitama-soil.js','utf8'),box);
assert.equal(box.gxSaitamaSoilValidate(),true);
assert.equal(box.GX_SAITAMA_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_SAITAMA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_SAITAMA_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxSaitamaSoilPanel('09'),'');
assert.equal(box.gxSaitamaSoilPanel('10'),'');
const html=box.gxSaitamaSoilPanel('11');
assert.match(html,/埼玉県の農耕地土壌GIS/);
assert.match(html,/1,912/);
assert.match(html,/73種類/);
assert.match(html,/215組合せ/);
assert.match(html,/17件/);
assert.match(html,/白岡町/);
assert.match(html,/鳩ヶ谷市/);
assert.match(html,/県外コード/);
assert.match(html,/要照合/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,216);
box.GX_SAITAMA_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxSaitamaSoilValidate(),/P38_SAITAMA_CODE_NAME_ANOMALY/);
box.GX_SAITAMA_CODE_NAME_PAIRS[0][2]--;
box.GX_SAITAMA_CODE_NAME_PAIRS[10][2]++;
assert.throws(()=>box.gxSaitamaSoilValidate(),/P38_SAITAMA_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const explorer=readFileSync('src/gx-data-explorer.js','utf8');
