import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p59-tottori-soil-shapefile-source-v1.json','utf8'));
const hash='a4bdf588790b48d87d445d25c03151caae781937b5ccb3b3054e574acf558915';
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,5198920);
assert.equal(m.source.members.length,7);
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1032);
assert.deepEqual(m.feature_counts_by_landuse,{'田':352,'普通畑':358,'牧草地':41,'樹園地':281});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,40);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,33);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'28':2});
assert.deepEqual(m.source_gun_quality.foreign_prefecture_gun_names,{'美方郡':2});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const a=spawnSync('python3',['scripts/p59-tottori-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(a.status,0,a.stderr);
assert.equal(JSON.parse(a.stdout).features,1032);
assert.equal(JSON.parse(a.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p59-tottori-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P59_TOTTORI_SOURCE_BLOCKED:ZIP_SIZE/);
const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-tottori-soil.js','utf8'),context);
assert.equal(context.gxTottoriSoilValidate(),true);
assert.equal(context.GX_TOTTORI_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_TOTTORI_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_TOTTORI_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(context.gxTottoriSoilPanel('30'),'');
const html=context.gxTottoriSoilPanel('31');
for(const term of ['鳥取県の農耕地土壌GIS','1,032件','兵庫県系JCODE','美方郡','40組合せ','33組合せ','要照合'])assert.ok(html.includes(term),term);
context.GX_TOTTORI_CODE_PAIRS[0][2]++;
assert.throws(()=>context.gxTottoriSoilValidate(),/P59_TOTTORI_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const run=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-tottori-soil.js'));
assert.ok(app.indexOf('src/gx-tottori-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxTottoriSoilPanel(current.code)'));
assert.ok(run.includes('python3 scripts/p59-tottori-soil-audit.py audit'));
assert.ok(run.includes('node tests/p59-tottori-soil-gis.test.mjs'));
console.log('NAFT_P59_TOTTORI_1032_FEATURES_40_JCODE_PAIRS_33_GUN_PAIRS_PASS');
