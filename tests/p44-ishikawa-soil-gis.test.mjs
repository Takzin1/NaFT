import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p44-ishikawa-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p44-ishikawa-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'石川県.zip');
assert.equal(m.source.source_zip_sha256,'84cb6318af859e65827319e613baa60ce9d0c2913d859dce3e9c3f1c0050f9ad');
assert.equal(m.source.zip_bytes,3522275);
assert.equal(m.source.uncompressed_bytes,5802534);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((a,r)=>a+r.bytes,0),5802534);
assert.ok(m.source.members.every(r=>r.name.startsWith('k20石川県.')&&/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,630);
assert.equal(m.geometry.municipality_name_count,19);
assert.equal(m.geometry.unique_jcodes,22);
assert.equal(m.geometry.administrative_code_name_pairs,47);
assert.deepEqual(m.geometry.bounds_lon_lat,[136.2509378621368,36.16399276652885,137.35953704185152,37.528077919581506]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':630});
assert.deepEqual(m.geometry.gun_counts,{'':434,'河北郡':31,'石川郡':5,'羽咋郡':73,'能美郡':10,'鳳珠郡':59,'鹿島郡':18});
assert.deepEqual(m.feature_counts_by_landuse,{'田':309,'普通畑':198,'牧草地':33,'樹園地':90});
assert.equal(m.soil_group_code_categories,18);
assert.equal(m.soil_fine_class_categories,59);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,47);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,47);
assert.equal(new Set(pairs.map(r=>r[0])).size,22);
assert.equal(new Set(pairs.map(r=>r[1])).size,19);
assert.ok(pairs.every(r=>r.length===6&&/^(16|17)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((s,r)=>s+r[i+2],0)),[309,198,33,90]);
const a=m.source_code_name_anomalies;
const foreign=pairs.filter(r=>r[0].startsWith('16'));
assert.equal(foreign.length,3);
assert.equal(foreign.reduce((s,r)=>s+r.slice(2).reduce((x,y)=>x+y,0),0),5);
assert.deepEqual(a.foreign_prefecture_code_pairs,foreign);
assert.deepEqual(a.foreign_prefixes,['16']);
assert.deepEqual(a.foreign_code_prefix_totals,{'16':5});
assert.equal(Object.keys(a.codes_with_multiple_names).length,11);
assert.equal(Object.keys(a.names_with_multiple_codes).length,14);
assert.equal(a.one_to_one_code_name_mapping,false);
assert.equal(a.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
assert.deepEqual(a.historical_place_names_as_source,['野々市町']);
assert.deepEqual(a.historical_place_name_polygon_counts,{'野々市町':11});
assert.equal(pairs.filter(r=>r[1]==='野々市町').reduce((s,r)=>s+r.slice(2).reduce((x,y)=>x+y,0),0),11);

const gunPairs=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunPairs.length,29);
assert.equal(new Set(gunPairs.map(r=>r[0]+'|'+r[1])).size,29);
assert.deepEqual([0,1,2,3].map(i=>gunPairs.reduce((s,r)=>s+r[i+2],0)),[309,198,33,90]);
assert.deepEqual(gunPairs.find(r=>r[0]==='羽咋郡'&&r[1]==='中能登町'),['羽咋郡','中能登町',1,0,0,0]);
const byGun=Object.fromEntries([...new Set(gunPairs.map(r=>r[0]))].map(k=>[k,gunPairs.filter(r=>r[0]===k).reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(byGun,m.geometry.gun_counts);
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs.length,1);
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs[0].jcode,'17384');
assert.equal(m.source_gun_anomalies.suspicious_gun_name_pairs[0].polygons,1);
assert.equal(m.source_gun_anomalies.resolution,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_NORMALIZATION');

const checked=spawnSync('python3',['scripts/p44-ishikawa-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(checked.status,0,checked.stderr);
assert.equal(JSON.parse(checked.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(JSON.parse(checked.stdout).raw_original_verified_in_ci,false);
const badZip=spawnSync('python3',['scripts/p44-ishikawa-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(badZip.status,0);
assert.match(badZip.stderr,/P44_ISHIKAWA_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:x=>String(x).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-ishikawa-soil.js','utf8'),box);
assert.equal(box.gxIshikawaSoilValidate(),true);
assert.equal(box.GX_ISHIKAWA_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_ISHIKAWA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_ISHIKAWA_GUN_NAME_PAIRS)),gunPairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_ISHIKAWA_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_ISHIKAWA_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(box.gxIshikawaSoilPanel('15'),'');
assert.equal(box.gxIshikawaSoilPanel('16'),'');
assert.equal(box.gxIshikawaSoilPanel('18'),'');
const html=box.gxIshikawaSoilPanel('17');
assert.match(html,/石川県の農耕地土壌GIS/);
assert.match(html,/630件/);
assert.match(html,/19種類/);
assert.match(html,/47通り/);
assert.match(html,/5ポリゴン/);
assert.match(html,/野々市町/);
assert.match(html,/羽咋郡／中能登町/);
assert.match(html,/郡名不整合/);
assert.match(html,/要照合/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,85); // 6 gun + 29 gun/name + 47 code/name + 3 headers

box.GX_ISHIKAWA_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxIshikawaSoilValidate(),/P44_ISHIKAWA_CODE_NAME_ANOMALY/);
box.GX_ISHIKAWA_CODE_NAME_PAIRS[0][2]--;
box.GX_ISHIKAWA_CODE_NAME_PAIRS[7][2]++;
assert.throws(()=>box.gxIshikawaSoilValidate(),/P44_ISHIKAWA_TOTAL/);
box.GX_ISHIKAWA_CODE_NAME_PAIRS[7][2]--;
box.GX_ISHIKAWA_GUN_NAME_PAIRS.find(r=>r[0]==='羽咋郡'&&r[1]==='中能登町')[2]++;
assert.throws(()=>box.gxIshikawaSoilValidate(),/P44_ISHIKAWA_GUN_PARITY|P44_ISHIKAWA_GUN_LANDUSE|P44_ISHIKAWA_NAKANOTO_GUN/);
const app=readFileSync('naft-app.html','utf8');
