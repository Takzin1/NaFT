import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const g=JSON.parse(readFileSync('research/p32-miyagi-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p32-miyagi-soil-shapefile-v1');
assert.equal(g.source.zip_bytes,10603446);
assert.equal(g.source.uncompressed_bytes,16787142);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((sum,m)=>sum+m.bytes,0),16787142);
assert.match(g.source.source_zip_sha256,/^[0-9a-f]{64}$/);
assert.equal(g.source.source_zip_sha256,'d6f9d7f637ae210d269c806aafcea6b9498c9cc3ff37068db4ae012bc6606c4f');
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.geometry.shape_count,1588);
assert.equal(g.geometry.administrative_code_units,39);
assert.equal(g.geometry.sendai_ward_units,5);
assert.equal(g.geometry.municipality_equivalent_groups,35);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.geometry.bounds_lon_lat,[140.28617994472927,37.750934461853944,141.67068446607755,38.981866385479684]);
assert.deepEqual(g.feature_counts_by_landuse,{'田':625,'普通畑':551,'牧草地':216,'樹園地':196});
assert.equal(g.soil_group_code_categories,16);
assert.equal(g.soil_fine_class_categories,96);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.deepEqual(g.historic_place_names_as_source,['富谷町']);
assert.equal(g.administrative_units_counts_by_landuse.length,39);
assert.equal(new Set(g.administrative_units_counts_by_landuse.map(row=>row[0])).size,39);
assert.equal(g.administrative_units_counts_by_landuse.filter(row=>row[0].startsWith('0410')).length,5);
assert.ok(g.administrative_units_counts_by_landuse.some(row=>row[0]==='04423'&&row[1]==='富谷町'));
assert.deepEqual([0,1,2,3].map(i=>g.administrative_units_counts_by_landuse.reduce((n,row)=>n+row[2+i],0)),[625,551,216,196]);

const audit=spawnSync('python3',['scripts/p32-miyagi-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
const reject=spawnSync('python3',['scripts/p32-miyagi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(reject.status,0);
assert.match(reject.stderr,/P32_MIYAGI_SOURCE_BLOCKED:ZIP_SIZE/);

const sandbox={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(sandbox);
vm.runInContext(readFileSync('src/gx-miyagi-soil.js','utf8'),sandbox);
assert.equal(sandbox.gxMiyagiSoilValidate(),true);
assert.equal(sandbox.GX_MIYAGI_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(sandbox.GX_MIYAGI_ADMIN_UNITS)),g.administrative_units_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(sandbox.GX_MIYAGI_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(sandbox.gxMiyagiSoilPanel('01'),'');
assert.equal(sandbox.gxMiyagiSoilPanel('03'),'');
const html=sandbox.gxMiyagiSoilPanel('04');
assert.match(html,/宮城県の農耕地土壌GIS/);
assert.match(html,/1,588/);
assert.match(html,/39行政区分/);
assert.match(html,/仙台市の5区/);
assert.match(html,/富谷町/);
assert.match(html,/原本ハッシュ/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,40);
sandbox.GX_MIYAGI_ADMIN_UNITS[0][2]++;
assert.throws(()=>sandbox.gxMiyagiSoilValidate(),/P32_MIYAGI_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-miyagi-soil.js')>0);
assert.ok(app.indexOf('src/gx-miyagi-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxMiyagiSoilPanel(current.code)'));
assert.ok(gx.includes('gxHokkaidoSoilPanel(current.code)'));
assert.ok(gx.includes('gxAomoriSoilPanel(current.code)'));
assert.ok(gx.includes('gxIwateSoilPanel(current.code)'));
console.log('NAFT_P32_MIYAGI_SOIL_GIS_INTAKE_AND_UI_PASS');
