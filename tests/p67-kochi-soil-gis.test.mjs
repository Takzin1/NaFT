import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p67-kochi-soil-shapefile-source-v1.json','utf8'));
const hash='783d8be4ba99102f30a136ac056227eceff4b1d36d7b212e52de1b0f7d5769af';
assert.equal(m.schema,'naft-p67-kochi-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,5950368);
assert.equal(m.source.uncompressed_bytes,9460292);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,767);
assert.equal(m.geometry.municipality_name_count,34);
assert.equal(m.geometry.unique_jcodes,37);
assert.deepEqual(m.feature_counts_by_landuse,{'田':334,'普通畑':228,'牧草地':34,'樹園地':171});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,63);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,50);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'38':6});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,6);
assert.equal(m.source_gun_quality.blank_gun_features,379);
assert.equal(m.source_gun_quality.non_kochi_gun_name_feature_count,6);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,92);
assert.equal(Object.keys(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name).length,6);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const publicAudit=spawnSync('python3',['scripts/p67-kochi-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(publicAudit.status,0,publicAudit.stderr);
assert.equal(JSON.parse(publicAudit.stdout).features,767);
assert.equal(JSON.parse(publicAudit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p67-kochi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P67_KOCHI_SOURCE_BLOCKED:ZIP_BYTES/);
const ctx={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(ctx);
vm.runInContext(readFileSync('src/gx-kochi-soil.js','utf8'),ctx);
assert.equal(ctx.gxKochiSoilValidate(),true);
assert.equal(ctx.GX_KOCHI_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KOCHI_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.GX_KOCHI_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(ctx.gxKochiSoilPanel('38'),'');
const html=ctx.gxKochiSoilPanel('39');
for(const s of ['高知県の農耕地土壌GIS','767件','愛媛県系JCODE','上浮穴郡','北宇和郡','南宇和郡','63組合せ','50組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
ctx.GX_KOCHI_CODE_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKochiSoilValidate(),/P67_KOCHI_/);
ctx.GX_KOCHI_CODE_PAIRS[0][2]--;
assert.equal(ctx.gxKochiSoilValidate(),true);
ctx.GX_KOCHI_GUN_PAIRS[0][2]++;
assert.throws(()=>ctx.gxKochiSoilValidate(),/P67_KOCHI_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-kochi-soil.js'));
assert.ok(app.indexOf('src/gx-kochi-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxEhimeSoilPanel(current.code)'));
assert.ok(atlas.includes('gxKochiSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p67-kochi-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p67-kochi-soil-gis.test.mjs'));
console.log('NAFT_P67_KOCHI_767_POLYGONS_63_JCODE_PAIRS_50_GUN_PAIRS_PASS');
