import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p63-yamaguchi-soil-shapefile-source-v1.json','utf8'));
const hash='9331249a4b2fef18bba89979954c06a12ea69e8c33708aa1b89282f66c50d957';
assert.equal(m.schema,'naft-p63-yamaguchi-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,8786845);
assert.equal(m.source.uncompressed_bytes,13708960);
assert.equal(m.source.members.length,7);
assert.ok(m.source.members.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1033);
assert.equal(m.geometry.unique_jcodes,22);
assert.equal(m.geometry.municipality_name_count,19);
assert.deepEqual(m.feature_counts_by_landuse,{'田':483,'普通畑':276,'牧草地':59,'樹園地':215});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,46);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,25);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'32':3,'34':1});
assert.equal(m.source_code_name_anomalies.foreign_prefecture_code_feature_count,4);
assert.equal(m.source_gun_quality.blank_gun_features,890);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,195);
assert.equal(m.source_gun_quality.non_yamaguchi_gun_name_feature_count,3);
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const audit=spawnSync('python3',['scripts/p63-yamaguchi-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(audit.status,0,audit.stderr);
assert.equal(JSON.parse(audit.stdout).features,1033);
assert.equal(JSON.parse(audit.stdout).private_zip_checked_in_ci,false);
const invalid=spawnSync('python3',['scripts/p63-yamaguchi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(invalid.status,0);
assert.match(invalid.stderr,/P63_YAMAGUCHI_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-yamaguchi-soil.js','utf8'),context);
assert.equal(context.gxYamaguchiSoilValidate(),true);
assert.equal(context.GX_YAMAGUCHI_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_YAMAGUCHI_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_YAMAGUCHI_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(context.gxYamaguchiSoilPanel('34'),'');
const html=context.gxYamaguchiSoilPanel('35');
for(const s of ['山口県の農耕地土壌GIS','1,033件','県外系JCODE','鹿足郡','46組合せ','25組合せ','要照合','農地面積ha'])assert.ok(html.includes(s),s);
context.GX_YAMAGUCHI_CODE_PAIRS[0][2]++;
assert.throws(()=>context.gxYamaguchiSoilValidate(),/P63_YAMAGUCHI_/);
context.GX_YAMAGUCHI_CODE_PAIRS[0][2]--;
assert.equal(context.gxYamaguchiSoilValidate(),true);
context.GX_YAMAGUCHI_GUN_PAIRS[0][2]++;
assert.throws(()=>context.gxYamaguchiSoilValidate(),/P63_YAMAGUCHI_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-yamaguchi-soil.js'));
assert.ok(app.indexOf('src/gx-yamaguchi-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxHiroshimaSoilPanel(current.code)'));
assert.ok(atlas.includes('gxYamaguchiSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p63-yamaguchi-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p63-yamaguchi-soil-gis.test.mjs'));
console.log('NAFT_P63_YAMAGUCHI_1033_POLYGONS_46_JCODE_PAIRS_25_GUN_PAIRS_PASS');
