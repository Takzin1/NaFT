import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const m=JSON.parse(readFileSync('research/p61-okayama-soil-shapefile-source-v1.json','utf8'));
const hash='beb5ffe3f03d788641d952b9d51621ee1d70612d7bd544b82b03476d94b3b47d';
assert.equal(m.schema,'naft-p61-okayama-soil-shapefile-v1');
assert.equal(m.source.source_zip_sha256,hash);
assert.equal(m.source.zip_bytes,13379023);
assert.equal(m.source.members.length,7);
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.geometry.shape_count,1151);
assert.equal(m.geometry.unique_jcodes,33);
assert.equal(m.geometry.municipality_name_count,30);
assert.deepEqual(m.feature_counts_by_landuse,{'田':489,'普通畑':337,'牧草地':74,'樹園地':251});
assert.equal(m.jcode_name_pairs_counts_by_landuse.length,80);
assert.equal(m.gun_name_pairs_counts_by_landuse.length,43);
assert.deepEqual(m.source_code_name_anomalies.foreign_code_prefix_totals,{'28':2,'31':2});
assert.equal(m.source_gun_quality.blank_gun_features,891);
assert.equal(m.source_gun_quality.empty_gun_features_for_names_with_county_elsewhere,222);
assert.deepEqual(m.source_gun_quality.multiple_nonempty_guns_per_municipality_name,{'真庭市':['日野郡','東伯郡']});
assert.equal(m.scientific_boundaries.calculation_of_certified_credits_prohibited,true);
const a=spawnSync('python3',['scripts/p61-okayama-soil-audit.py','audit'],{encoding:'utf8',timeout:30000});
assert.equal(a.status,0,a.stderr);
assert.equal(JSON.parse(a.stdout).features,1151);
assert.equal(JSON.parse(a.stdout).private_zip_checked_in_ci,false);
const bad=spawnSync('python3',['scripts/p61-okayama-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:30000});
assert.notEqual(bad.status,0);
assert.match(bad.stderr,/P61_OKAYAMA_SOURCE_BLOCKED:ORIGINAL_ZIP_SIZE/);
const context={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(context);
vm.runInContext(readFileSync('src/gx-okayama-soil.js','utf8'),context);
assert.equal(context.gxOkayamaSoilValidate(),true);
assert.equal(context.GX_OKAYAMA_SOURCE_SHA,hash);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_OKAYAMA_CODE_PAIRS)),m.jcode_name_pairs_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(context.GX_OKAYAMA_GUN_PAIRS)),m.gun_name_pairs_counts_by_landuse);
assert.equal(context.gxOkayamaSoilPanel('32'),'');
const html=context.gxOkayamaSoilPanel('33');
for(const word of ['岡山県の農耕地土壌GIS','1,151件','県外系JCODE','佐用郡','80組合せ','43組合せ','要照合','農地面積ha'])assert.ok(html.includes(word),word);
context.GX_OKAYAMA_CODE_PAIRS[0][2]++;
assert.throws(()=>context.gxOkayamaSoilValidate(),/P61_OKAYAMA_/);
context.GX_OKAYAMA_CODE_PAIRS[0][2]--;
assert.equal(context.gxOkayamaSoilValidate(),true);
context.GX_OKAYAMA_GUN_PAIRS[0][2]++;
assert.throws(()=>context.gxOkayamaSoilValidate(),/P61_OKAYAMA_/);
const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.includes('src/gx-okayama-soil.js'));
assert.ok(app.indexOf('src/gx-okayama-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxShimaneSoilPanel(current.code)'));
assert.ok(atlas.includes('gxOkayamaSoilPanel(current.code)'));
assert.ok(runner.includes('python3 scripts/p61-okayama-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p61-okayama-soil-gis.test.mjs'));
console.log('NAFT_P61_OKAYAMA_1151_POLYGONS_80_JCODE_PAIRS_43_GUN_PAIRS_PASS');
