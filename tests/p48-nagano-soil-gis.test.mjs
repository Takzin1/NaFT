const m=JSON.parse(readFileSync('research/p48-nagano-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p48-nagano-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'長野県.zip');
assert.equal(m.source.source_zip_sha256,'1760eeddfc65c44240dbb84ee221925c38814a705b65fe97cc6aeb4068b386fd');
assert.equal(m.source.zip_bytes,12941155);
assert.equal(m.source.uncompressed_bytes,21293734);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((total,r)=>total+r.bytes,0),21293734);
assert.ok(m.source.members.every(x=>x.name.startsWith('k16長野県.')&&/^[a-f0-9]{64}$/.test(x.sha256)));
assert.equal(m.source.original_zip_committed,false);
