assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
const cps=m.jcode_name_pairs_counts_by_landuse;
const gps=m.gun_name_pairs_counts_by_landuse;
assert.equal(cps.length,176);
assert.equal(gps.length,116);
assert.equal(new Set(cps.map(r=>r[0])).size,82);
assert.equal(new Set(cps.map(r=>r[1])).size,77);
assert.equal(new Set(cps.map(r=>r[0]+'|'+r[1])).size,176);
assert.equal(new Set(gps.map(r=>r[0]+'|'+r[1])).size,116);
assert.ok(cps.every(r=>r.length===6&&/^(10|15|19|20)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>cps.reduce((s,r)=>s+r[i+2],0)),[766,904,223,625]);
assert.deepEqual([0,1,2,3].map(i=>gps.reduce((s,r)=>s+r[i+2],0)),[766,904,223,625]);
const c=m.source_code_name_anomalies;
const foreign=cps.filter(r=>!r[0].startsWith('20'));
assert.equal(foreign.length,6);
assert.equal(foreign.reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0),10);
assert.deepEqual(c.foreign_prefecture_code_pairs,foreign);
assert.deepEqual(c.foreign_code_prefix_totals,{'10':3,'15':2,'19':5});
