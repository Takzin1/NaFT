assert.deepEqual(Object.keys(q.municipality_names_with_multiple_nonempty_guns).sort(),['松川町','栄村','池田町','軽井沢町','長和町'].sort());
assert.deepEqual(q.municipality_names_with_multiple_nonempty_guns['栄村'],['下水内郡','下高井郡','中魚沼郡']);
assert.equal(q.status,'UNRESOLVED_ORIGINAL_KEPT_NO_GUN_JOIN');

