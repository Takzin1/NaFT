assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,2518);
assert.deepEqual(m.geometry.bounds_lon_lat,[137.4472894680439,35.203588111443956,138.70208377936234,37.00325490200541]);
assert.equal(m.geometry.municipality_name_count,77);
assert.equal(m.geometry.unique_jcodes,82);
assert.equal(m.geometry.administrative_code_name_pairs,176);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
