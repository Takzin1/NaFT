assert.equal(m.geometry.gun_counts['甘楽郡'],2);
assert.equal(m.geometry.gun_counts['吾妻郡'],1);
const derivedGun=Object.fromEntries([...new Set(gps.map(r=>r[0]))].map(g=>[g,gps.filter(r=>r[0]===g).reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0)]));
