import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';

const m=JSON.parse(readFileSync('research/p45-toyama-soil-shapefile-source-v1.json','utf8'));
assert.equal(m.schema,'naft-p45-toyama-soil-shapefile-v1');
assert.equal(m.source.provided_filename,'富山県.zip');
assert.equal(m.source.source_zip_sha256,'fbbe882b713db76fc18fde6106cdbaeb2a82a2302e97b1cb8dc33b1d8cc19ab7');
assert.equal(m.source.zip_bytes,4675546);
assert.equal(m.source.uncompressed_bytes,7481198);
assert.equal(m.source.members.length,7);
assert.equal(m.source.members.reduce((sum,r)=>sum+r.bytes,0),7481198);
assert.ok(m.source.members.every(r=>r.name.startsWith('k19富山県.')&&/^[a-f0-9]{64}$/.test(r.sha256)));
assert.equal(m.source.original_zip_committed,false);
assert.equal(m.source.raw_geometry_committed,false);
assert.equal(m.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(m.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(m.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(m.geometry.type,'POLYGON');
assert.equal(m.geometry.crs,'GCS_JGD_2000');
assert.equal(m.geometry.shape_count,632);
assert.equal(m.geometry.municipality_name_count,15);
assert.equal(m.geometry.unique_jcodes,15);
assert.equal(m.geometry.administrative_code_name_pairs,36);
assert.deepEqual(m.geometry.bounds_lon_lat,[136.78498869633378,36.34960657076776,137.65754674358115,36.97336380774928]);
assert.deepEqual(m.geometry.sicho_unique_values,['']);
assert.deepEqual(m.geometry.sicho_counts,{'':632});
assert.deepEqual(m.geometry.gun_counts,{'':495,'下新川郡':50,'中新川郡':87});
assert.deepEqual(m.feature_counts_by_landuse,{'田':428,'普通畑':116,'牧草地':18,'樹園地':70});
assert.equal(m.soil_group_code_categories,15);
assert.equal(m.soil_fine_class_categories,59);
assert.equal(m.scientific_boundaries.official_credit_tco2e,null);
assert.equal(m.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(m.scientific_boundaries.gun_name_missingness_detected,true);
assert.equal(m.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);

const pairs=m.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,36);
assert.equal(new Set(pairs.map(r=>r[0])).size,15);
assert.equal(new Set(pairs.map(r=>r[1])).size,15);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,36);
assert.ok(pairs.every(r=>r.length===6&&/^16[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((sum,r)=>sum+r[i+2],0)),[428,116,18,70]);
const anomalies=m.source_code_name_anomalies;
assert.equal(anomalies.foreign_prefecture_code_feature_count,0);
assert.deepEqual(anomalies.foreign_prefecture_code_pairs,[]);
assert.deepEqual(anomalies.foreign_prefixes,[]);
assert.deepEqual(anomalies.foreign_code_prefix_totals,{});
assert.equal(Object.keys(anomalies.codes_with_multiple_names).length,10);
assert.equal(Object.keys(anomalies.names_with_multiple_codes).length,12);
assert.equal(anomalies.one_to_one_code_name_mapping,false);
assert.equal(anomalies.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');

const gunRows=m.gun_name_pairs_counts_by_landuse;
assert.equal(gunRows.length,19);
assert.equal(new Set(gunRows.map(r=>r[0]+'|'+r[1])).size,19);
assert.deepEqual([0,1,2,3].map(i=>gunRows.reduce((sum,r)=>sum+r[i+2],0)),[428,116,18,70]);
const totals=Object.fromEntries([...new Set(gunRows.map(r=>r[0]))].map(g=>[g,gunRows.filter(r=>r[0]===g).reduce((n,r)=>n+r.slice(2).reduce((a,b)=>a+b,0),0)]));
assert.deepEqual(totals,m.geometry.gun_counts);
const missing=m.source_gun_quality.empty_gun_name_pairs_with_nonempty_gun_elsewhere;
assert.equal(m.source_gun_quality.empty_gun_features_for_known_gun_towns,25);
assert.equal(m.source_gun_quality.status,'SOURCE_NULL_PRESERVED_GUN_COMPLETENESS_PENDING');
assert.equal(missing.length,4);
assert.deepEqual(Object.fromEntries(missing.map(r=>[r.municipality_name,r.empty_gun_polygon_count])),
                 {'上市町':15,'入善町':5,'立山町':1,'舟橋村':4});
assert.equal(missing.reduce((a,r)=>a+r.empty_gun_polygon_count,0),25);
for(const row of missing){
 const original=gunRows.find(r=>r[0]===''&&r[1]===row.municipality_name);
 assert.ok(original);
 assert.equal(original.slice(2).reduce((a,b)=>a+b,0),row.empty_gun_polygon_count);
 assert.ok(gunRows.some(r=>r[0]===row.gun_names_seen_elsewhere[0]&&r[1]===row.municipality_name));
}

const audit=spawnSync('python3',['scripts/p45-toyama-soil-audit.py','audit'],{encoding:'utf8',timeout:12000});
assert.equal(audit.status,0,audit.stderr);
const outcome=JSON.parse(audit.stdout);
assert.equal(outcome.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(outcome.raw_original_verified_in_ci,false);
assert.equal(outcome.polygons,632);
const wrong=spawnSync('python3',['scripts/p45-toyama-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:12000});
assert.notEqual(wrong.status,0);
assert.match(wrong.stderr,/P45_TOYAMA_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-toyama-soil.js','utf8'),box);
assert.equal(box.gxToyamaSoilValidate(),true);
assert.equal(box.GX_TOYAMA_SOURCE_HASH,m.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_TOYAMA_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_TOYAMA_GUN_NAME_PAIRS)),gunRows);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_TOYAMA_GUN))),m.geometry.gun_counts);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_TOYAMA_EMPTY_GUN_KNOWN_TOWNS)),missing);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_TOYAMA_LANDUSE))),m.feature_counts_by_landuse);
assert.equal(box.gxToyamaSoilPanel('17'),'');
assert.equal(box.gxToyamaSoilPanel('15'),'');
const html=box.gxToyamaSoilPanel('16');
assert.match(html,/富山県の農耕地土壌GIS/);
assert.match(html,/632件/);
assert.match(html,/428件/);
assert.match(html,/36通り/);
assert.match(html,/県外JCODEは0件/);
assert.match(html,/GUNが空欄の原本レコードが計25件/);
assert.match(html,/上市町/);
assert.match(html,/入善町/);
assert.match(html,/立山町/);
assert.match(html,/舟橋村/);
assert.match(html,/要照合/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,60);
box.GX_TOYAMA_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxToyamaSoilValidate(),/P45_TOYAMA_TOTAL/);
box.GX_TOYAMA_CODE_NAME_PAIRS[0][2]--;
box.GX_TOYAMA_GUN_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxToyamaSoilValidate(),/P45_TOYAMA_GUN_PARITY/);
box.GX_TOYAMA_GUN_NAME_PAIRS[0][2]--;

const app=readFileSync('naft-app.html','utf8');
const atlas=readFileSync('src/gx-data-explorer.js','utf8');
const runner=readFileSync('tests/run.sh','utf8');
assert.ok(app.indexOf('src/gx-toyama-soil.js')>0);
assert.ok(app.indexOf('src/gx-toyama-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(atlas.includes('gxToyamaSoilPanel(current.code)'));
for(const name of ['Hokkaido','Aomori','Iwate','Miyagi','Yamagata','Akita','Fukushima','Ibaraki','Tochigi','Saitama','Gunma','Tokyo','Chiba','Kanagawa','Niigata','Ishikawa']){
 assert.ok(atlas.includes('gx'+name+'SoilPanel(current.code)'));
}
assert.ok(runner.includes('python3 scripts/p45-toyama-soil-audit.py audit'));
assert.ok(runner.includes('node tests/p45-toyama-soil-gis.test.mjs'));
console.log('NAFT_P45_TOYAMA_632_SOURCE_CODE_36_GUN_19_MISSING_25_GUARDS_PASS');
