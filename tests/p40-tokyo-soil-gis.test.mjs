assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_TOKYO_LANDUSE))),g.feature_counts_by_landuse);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_TOKYO_SICHO))),g.geometry.sicho_counts);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_TOKYO_ISLAND_PAIRS)),g.tokyo_subprefectures.island_subprefecture_name_pairs);
