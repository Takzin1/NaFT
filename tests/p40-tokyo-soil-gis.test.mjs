assert.equal(g.source.provided_filename,'東京都(1).zip');
assert.equal(g.source.source_zip_sha256,'b4dcede3f7664f4366d7d6ab5ead2c06314602c8c9d691a946d90984af3d9c1e');
assert.equal(g.source.zip_bytes,1227836);
assert.equal(g.source.uncompressed_bytes,2371330);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((a,m)=>a+m.bytes,0),2371330);
assert.ok(g.source.members.every(m=>m.name.startsWith('k13東京都.')&&/^[a-f0-9]{64}$/.test(m.sha256)));
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(g.geometry.shape_count,472);
assert.equal(g.geometry.municipality_name_count,43);
assert.equal(g.geometry.unique_jcodes,47);
assert.equal(g.geometry.administrative_code_name_pairs,87);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.bounds_lon_lat,[138.9725498740143,33.06049025736573,139.85639982273338,35.84624892212051]);
assert.deepEqual(g.geometry.sicho_unique_values,['','三宅支庁','八丈支庁','大島支庁']);
assert.deepEqual(g.geometry.sicho_counts,{'':451,'三宅支庁':6,'八丈支庁':6,'大島支庁':9});
assert.deepEqual(g.geometry.gun_counts,{'':440,'西多摩郡':32});
assert.deepEqual(g.tokyo_subprefectures.sicho_feature_counts,g.geometry.sicho_counts);
assert.deepEqual(g.tokyo_subprefectures.gun_feature_counts,g.geometry.gun_counts);
assert.equal(g.tokyo_subprefectures.island_subprefecture_name_pairs.length,6);
assert.ok(g.tokyo_subprefectures.island_subprefecture_name_pairs.some(r=>r[0]==='八丈支庁'&&r[1]==='八丈町'));
assert.ok(g.tokyo_subprefectures.island_subprefecture_name_pairs.some(r=>r[0]==='三宅支庁'&&r[1]==='三宅村'));
assert.equal(g.tokyo_subprefectures.missing_municipalities_do_not_imply_missing_gis_source,true);
assert.deepEqual(g.feature_counts_by_landuse,{'田':48,'普通畑':248,'牧草地':5,'樹園地':171});
assert.equal(g.soil_group_code_categories,15);
assert.equal(g.soil_fine_class_categories,30);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.scientific_boundaries.jcode_name_conflict_detected,true);
assert.equal(g.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
const rows=g.jcode_name_pairs_counts_by_landuse;
assert.equal(rows.length,87);
assert.equal(new Set(rows.map(r=>r[0])).size,47);
assert.equal(new Set(rows.map(r=>r[1])).size,43);
assert.equal(new Set(rows.map(r=>r[0]+'|'+r[1])).size,87);
assert.ok(rows.every(r=>r.length===6&&/^(11|13)[0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>rows.reduce((a,r)=>a+r[2+i],0)),[48,248,5,171]);
const a=g.source_code_name_anomalies;
const foreign=rows.filter(r=>r[0].startsWith('11'));
assert.equal(foreign.length,8);
assert.equal(foreign.reduce((s,r)=>s+r.slice(2).reduce((x,y)=>x+y,0),0),15);
assert.deepEqual(foreign,a.foreign_prefecture_code_pairs);
assert.deepEqual(a.foreign_prefixes,['11']);
assert.deepEqual(a.foreign_code_prefix_totals,{'11':15});
assert.equal(Object.keys(a.codes_with_multiple_names).length,23);
assert.equal(Object.keys(a.names_with_multiple_codes).length,26);
assert.equal(a.one_to_one_code_name_mapping,false);
assert.equal(a.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
const audit=spawnSync('python3',['scripts/p40-tokyo-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const outcome=JSON.parse(audit.stdout);
assert.equal(outcome.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(outcome.raw_original_verified_in_ci,false);
const wrong=spawnSync('python3',['scripts/p40-tokyo-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(wrong.status,0);
