import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const g=JSON.parse(readFileSync('research/p37-tochigi-soil-shapefile-source-v1.json','utf8'));
assert.equal(g.schema,'naft-p37-tochigi-soil-shapefile-v1');
assert.equal(g.source.source_zip_sha256,'780db24d2bdb7f088e3c8f203bb52cbe20c9789534651b6327455d42f3b2b1c4');
assert.equal(g.source.zip_bytes,13379287);
assert.equal(g.source.uncompressed_bytes,21266034);
assert.equal(g.source.members.length,7);
assert.equal(g.source.members.reduce((s,m)=>s+m.bytes,0),21266034);
assert.ok(g.source.members.every(m=>m.name.startsWith('k9栃木県.')&&/^[a-f0-9]{64}$/.test(m.sha256)));
assert.equal(g.source.original_zip_committed,false);
assert.equal(g.source.raw_geometry_committed,false);
assert.equal(g.source.publisher_authentication,'NOT_VERIFIED');
assert.equal(g.source.redistribution_rights,'NOT_VERIFIED');
assert.equal(g.source.source_match,'CONSISTENT_METADATA_NO_OFFICIAL_ZIP_SHA_COMPARISON');
assert.equal(g.geometry.shape_count,1798);
assert.equal(g.geometry.municipality_name_count,26);
assert.equal(g.geometry.unique_jcodes,32);
assert.equal(g.geometry.administrative_code_name_pairs,85);
assert.equal(g.geometry.crs,'GCS_JGD_2000');
assert.deepEqual(g.geometry.bounds_lon_lat,[139.36266168493395,36.202170868189896,140.27868234459973,37.1355197419129]);
assert.deepEqual(g.geometry.sicho_unique_values,['']);
assert.deepEqual(g.feature_counts_by_landuse,{'田':755,'普通畑':615,'牧草地':135,'樹園地':293});
assert.equal(g.soil_group_code_categories,14);
assert.equal(g.soil_fine_class_categories,96);
assert.equal(g.scientific_boundaries.official_credit_tco2e,null);
assert.equal(g.scientific_boundaries.municipality_level_aggregations_pending_reconciliation,true);
assert.equal(g.scientific_boundaries.jcode_name_conflict_detected,true);
const pairs=g.jcode_name_pairs_counts_by_landuse;
assert.equal(pairs.length,85);
assert.equal(new Set(pairs.map(r=>r[0])).size,32);
assert.equal(new Set(pairs.map(r=>r[1])).size,26);
assert.equal(new Set(pairs.map(r=>r[0]+'|'+r[1])).size,85);
assert.ok(pairs.every(r=>r.length===6&&/^0[89][0-9]{3}$/.test(r[0])));
assert.deepEqual([0,1,2,3].map(i=>pairs.reduce((a,r)=>a+r[i+2],0)),[755,615,135,293]);
const conflicts=g.source_code_name_anomalies;
const foreign=pairs.filter(r=>r[0].startsWith('08'));
assert.equal(foreign.length,7);
assert.equal(foreign.reduce((s,r)=>s+r.slice(2).reduce((a,b)=>a+b,0),0),19);
assert.deepEqual(foreign,conflicts.foreign_prefecture_code_pairs);
assert.deepEqual([...new Set(foreign.map(r=>r[0]))].sort(),conflicts.distinct_foreign_prefecture_codes);
assert.equal(conflicts.foreign_prefecture_code_feature_count,19);
assert.equal(Object.keys(conflicts.codes_with_multiple_names).length,19);
assert.equal(Object.keys(conflicts.names_with_multiple_codes).length,23);
assert.deepEqual(conflicts.historical_place_name_in_source,['岩舟町']);
assert.equal(pairs.filter(r=>r[1]==='岩舟町').reduce((a,r)=>a+r.slice(2).reduce((x,y)=>x+y,0),0),51);
assert.equal(conflicts.status,'UNRESOLVED_ORIGINAL_KEPT_NO_CITY_JOIN');
assert.equal(conflicts.one_to_one_code_name_mapping,false);

const audit=spawnSync('python3',['scripts/p37-tochigi-soil-audit.py','audit'],{encoding:'utf8',timeout:10000});
assert.equal(audit.status,0,audit.stderr);
const outcome=JSON.parse(audit.stdout);
assert.equal(outcome.status,'REGISTER_CONSISTENT_RAW_NOT_COMMITTED');
assert.equal(outcome.raw_original_verified_in_ci,false);
const wrong=spawnSync('python3',['scripts/p37-tochigi-soil-audit.py','verify','/dev/null'],{encoding:'utf8',timeout:10000});
assert.notEqual(wrong.status,0);
assert.match(wrong.stderr,/P37_TOCHIGI_SOURCE_BLOCKED:ZIP_SIZE/);

const box={gxEsc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;')};
vm.createContext(box);
vm.runInContext(readFileSync('src/gx-tochigi-soil.js','utf8'),box);
assert.equal(box.gxTochigiSoilValidate(),true);
assert.equal(box.GX_TOCHIGI_SOURCE_HASH,g.source.source_zip_sha256);
assert.deepEqual(JSON.parse(JSON.stringify(box.GX_TOCHIGI_CODE_NAME_PAIRS)),pairs);
assert.deepEqual(JSON.parse(JSON.stringify(Object.fromEntries(box.GX_TOCHIGI_LANDUSE))),g.feature_counts_by_landuse);
assert.equal(box.gxTochigiSoilPanel('08'),'');
assert.equal(box.gxTochigiSoilPanel('07'),'');
const html=box.gxTochigiSoilPanel('09');
assert.match(html,/栃木県の農耕地土壌GIS/);
assert.match(html,/1,798/);
assert.match(html,/26種類/);
assert.match(html,/85組合せ/);
assert.match(html,/19ポリゴン/);
assert.match(html,/岩舟町/);
assert.match(html,/08系/);
assert.match(html,/要照合/);
assert.match(html,/原本監査台帳/);
assert.match(html,/面積haではありません/);
assert.equal((html.match(/<tr>/g)||[]).length,86);
box.GX_TOCHIGI_CODE_NAME_PAIRS[0][2]++;
assert.throws(()=>box.gxTochigiSoilValidate(),/P37_TOCHIGI_TOTAL/);
const app=readFileSync('naft-app.html','utf8');
const gx=readFileSync('src/gx-data-explorer.js','utf8');
assert.ok(app.indexOf('src/gx-tochigi-soil.js')>0);
assert.ok(app.indexOf('src/gx-tochigi-soil.js')<app.indexOf('src/gx-data-explorer.js'));
assert.ok(gx.includes('gxTochigiSoilPanel(current.code)'));
